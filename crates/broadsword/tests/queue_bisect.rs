//! Post-merge judgments against real trains in isolated scratch repos.

use std::collections::BTreeMap;
use std::fs;
use std::path::{Path, PathBuf};
use std::process::{Command, Stdio};
use std::sync::atomic::{AtomicUsize, Ordering};
use std::time::{Duration, Instant};

mod support;

static COUNTER: AtomicUsize = AtomicUsize::new(0);
const GOOD: &str = "#[test]\nfn full_only() {}\n";
const BAD: &str = "#[test]\nfn full_only() { assert_eq!(1, 2); }\n";
const ROOT: &str = r#"
fn root() -> std::path::PathBuf {
    std::env::current_dir().unwrap().ancestors()
        .find(|p| p.join("broadsword.toml").is_file()).unwrap().to_path_buf()
}
"#;

fn git(dir: &Path, args: &[&str]) -> String {
    let out = Command::new("git")
        .args(args)
        .current_dir(dir)
        .stdin(Stdio::null())
        .output()
        .unwrap();
    assert!(out.status.success(), "git {args:?}: {:?}", out.stderr);
    String::from_utf8(out.stdout).unwrap().trim().into()
}

fn commit(dir: &Path, file: &str, contents: &str) {
    let path = dir.join(file);
    fs::create_dir_all(path.parent().unwrap()).unwrap();
    fs::write(path, contents).unwrap();
    git(dir, &["add", file]);
    git(dir, &["commit", "-qm", &format!("change {file}")]);
}

fn init_project(p: &Path) {
    fs::create_dir_all(p.join("src")).unwrap();
    fs::create_dir_all(p.join("tests")).unwrap();
    fs::write(
        p.join("Cargo.toml"),
        "[package]\nname = \"p\"\nversion = \"0.0.0\"\nedition = \"2021\"\n\n[workspace]\n",
    )
    .unwrap();
    fs::write(
        p.join("Cargo.lock"),
        "# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 3\n\n[[package]]\nname = \"p\"\nversion = \"0.0.0\"\n",
    )
    .unwrap();
    fs::write(p.join(".gitignore"), "target\n").unwrap();
    fs::write(p.join("src/lib.rs"), "").unwrap();
    fs::write(p.join("tests/smoke.rs"), "#[test]\nfn smoke() {}\n").unwrap();
    git(p, &["init", "-q", "-b", "main"]);
    for (key, value) in [
        ("user.name", "t"),
        ("user.email", "t@localhost"),
        ("core.autocrlf", "false"),
        ("commit.gpgsign", "false"),
    ] {
        git(p, &["config", key, value]);
    }
    git(p, &["add", "."]);
    git(p, &["commit", "-qm", "first"]);
}

type Record = BTreeMap<String, String>;

fn record(path: &Path) -> Record {
    fs::read_to_string(path)
        .unwrap()
        .lines()
        .filter_map(|line| line.split_once(" = "))
        .map(|(key, value)| (key.into(), value.into()))
        .collect()
}

struct Root {
    dir: PathBuf,
    fake: PathBuf,
}

impl Root {
    fn new(asynchronous: bool) -> Self {
        let n = COUNTER.fetch_add(1, Ordering::Relaxed);
        let dir = Path::new(env!("CARGO_MANIFEST_DIR"))
            .join("../../scratch")
            .join(format!("queue-bisect-{}-{n}", std::process::id()));
        fs::create_dir_all(dir.join("state/perf")).unwrap();
        let dir = fs::canonicalize(dir).unwrap();
        let dir = PathBuf::from(dir.to_string_lossy().trim_start_matches(r"\\?\"));
        let config = support::config(&[
            ("projects_dir", "\"scratch/projects\""),
            ("merge_train_max", "4"),
            (
                "queue_main_check_async",
                if asynchronous { "\"on\"" } else { "\"off\"" },
            ),
            ("queue_auto_revert", "\"on\""),
            ("merge_fast_tests", "\"p: smoke\""),
            ("reviewer_timeout_seconds", "30"),
            ("build_lock_wait_seconds", "120"),
            ("test_parallel_binaries", "8"),
        ]);
        fs::write(dir.join("broadsword.toml"), config).unwrap();
        let exe = Path::new(support::fake_claude());
        let fake = dir.join("scratch/reviewer").join(exe.file_name().unwrap());
        fs::create_dir_all(fake.parent().unwrap()).unwrap();
        fs::copy(exe, &fake).unwrap();
        init_project(&dir.join("scratch/projects/p"));
        Self { dir, fake }
    }

    fn p(&self) -> PathBuf {
        self.dir.join("scratch/projects/p")
    }

    fn queue(&self, name: &str) -> PathBuf {
        self.dir.join("state/queue").join(name)
    }

    fn entry(&self, id: &str) -> Record {
        record(&self.queue(&format!("{id}.entry")))
    }

    fn run(&self, args: &[&str], code: i32) -> String {
        let out = self.dir.join("scratch/command.out");
        let err = self.dir.join("scratch/command.err");
        let mut child = Command::new(support::bin())
            .args(args)
            .current_dir(&self.dir)
            .env("BROADSWORD_REVIEWER_CLI", &self.fake)
            .env("FAKE_CLAUDE_OUT_DIR", self.dir.join("fake-out"))
            .env("FAKE_CLAUDE_MODEL", "auto")
            .stdin(Stdio::null())
            .stdout(fs::File::create(&out).unwrap())
            .stderr(fs::File::create(&err).unwrap())
            .spawn()
            .unwrap();
        let start = Instant::now();
        let status = loop {
            if let Some(status) = child.try_wait().unwrap() {
                break status;
            }
            if start.elapsed() >= Duration::from_secs(240) {
                let _ = child.kill();
                let _ = child.wait();
                panic!("timed out: {args:?}\n{}", fs::read_to_string(&err).unwrap());
            }
            std::thread::sleep(Duration::from_millis(50));
        };
        let stdout = fs::read_to_string(out).unwrap();
        assert_eq!(
            status.code(),
            Some(code),
            "{args:?}\n{stdout}{}",
            fs::read_to_string(err).unwrap()
        );
        stdout
    }

    fn train_one(&self, file: &str, contents: &str) -> (String, String) {
        let task = self
            .run(&["task", "add", "p", "--title", file, "--claim", file], 0)
            .trim()
            .to_string();
        self.run(&["task", "start", &task, "--owner", "coder", "--worktree"], 0);
        commit(&self.dir.join("worktrees/p").join(&task), file, contents);
        let entry = self
            .run(&["queue", "add", &task, "--risk", "low", "--coder", "sonnet"], 0)
            .lines()
            .next()
            .unwrap()
            .trim()
            .to_string();
        (task, entry)
    }

    fn checks(&self) -> usize {
        fs::read_dir(self.dir.join("state/jobs"))
            .unwrap()
            .map(|entry| entry.unwrap().path())
            .filter(|p| p.extension().is_some_and(|ext| ext == "rec"))
            .map(|p| record(&p))
            .filter(|r| {
                r["kind"] == "check" && r["source"].replace('\\', "/") == "scratch/projects/p"
            })
            .count()
    }

    fn kill_orphan(&self) -> bool {
        let path = self.dir.join("pid");
        let Ok(raw) = fs::read_to_string(&path) else {
            return false;
        };
        let pid = raw.parse::<u32>().unwrap().to_string();
        let mut cmd = if cfg!(windows) {
            let mut c = Command::new("taskkill");
            c.args(["/F", "/PID", &pid]);
            c
        } else {
            let mut c = Command::new("kill");
            c.args(["-KILL", &pid]);
            c
        };
        let status = cmd
            .stdout(Stdio::null())
            .stderr(Stdio::null())
            .status()
            .unwrap();
        fs::remove_file(path).unwrap();
        status.success()
    }
}

impl Drop for Root {
    fn drop(&mut self) {
        self.kill_orphan();
        let _ = fs::remove_dir_all(&self.dir);
    }
}

#[test]
fn a_train_of_three_whose_third_member_breaks_a_test_reverts_only_the_third() {
    for asynchronous in [false, true] {
        let r = Root::new(asynchronous);
        commit(&r.p(), "tests/full.rs", GOOD);
        let (ta, a) = r.train_one("src/a.txt", "a\n");
        let (tb, b) = r.train_one("src/b.txt", "b\n");
        let (_, c) = r.train_one("tests/full.rs", BAD);
        r.run(&["queue", "run", "--all"], 6);
        let (a, b, entry) = (r.entry(&a), r.entry(&b), r.entry(&c));
        println!(
            "async={asynchronous}: first={}, second={}",
            a["status"], b["status"]
        );
        for (r_entry, task) in [(&a, ta), (&b, tb)] {
            assert_eq!(r_entry["status"], "merged", "{r_entry:?}");
            assert_eq!(r_entry["train"], entry["train"]);
            assert!(r_entry["log"].contains("kept on main: the bisect"));
            assert_eq!(
                record(&r.dir.join(format!("state/tasks/{task}.task")))["status"],
                "done"
            );
        }
        assert_eq!(entry["status"], "merged_check_failed");
        assert_eq!(entry["revert_check"], "passed");
        assert_eq!(entry["revert_from"], c);
        println!("main_bisect={}", entry["main_bisect"]);
        assert!(entry["main_bisect"].contains("(position 3 of 3)"));
        assert_eq!(git(&r.p(), &["rev-parse", "HEAD^"]), entry["main_sha"]);
        let message = git(&r.p(), &["log", "-1", "--format=%B"]);
        let reverted: Vec<_> = message
            .lines()
            .filter(|l| l.starts_with("This reverts commit "))
            .collect();
        let expected = format!("This reverts commit {}.", entry["main_sha"]);
        assert_eq!(reverted, [expected.as_str()]);
        assert_eq!(
            git(&r.p(), &["ls-tree", "-r", "HEAD"]),
            git(&r.p(), &["ls-tree", "-r", &b["main_sha"]])
        );
    }
}

fn flake_on_tip(asynchronous: bool, binaries: &[&str]) {
    let r = Root::new(asynchronous);
    let mut entries = vec![r.train_one("src/a.txt", "a\n").1];
    for name in binaries {
        let test = format!(
            "{ROOT}\n#[test]\nfn once() {{\n    let flag = root().join({name:?});\n    if flag.try_exists().unwrap() {{\n        std::fs::remove_file(flag).unwrap();\n        panic!(\"first run\");\n    }}\n}}\n"
        );
        entries.push(r.train_one(&format!("tests/{name}.rs"), &test).1);
        fs::write(r.dir.join(name), "").unwrap();
    }
    let out = r.run(&["queue", "run", "--all"], 0);
    for id in &entries {
        assert_eq!(r.entry(id)["status"], "merged", "{out}");
    }
    let last = r.entry(entries.last().unwrap());
    println!("async={asynchronous}: flake_rerun={}", last["flake_rerun"]);
    assert!(last["flake_rerun"].starts_with("pass:"), "{last:?}");
    for name in binaries {
        assert!(last["flake_rerun"].contains(&format!("--test {name}")));
    }
    assert_eq!(r.checks(), 2, "failure and a full confirmation on main");
    assert_eq!(git(&r.p(), &["rev-parse", "HEAD"]), last["main_sha"]);
    assert!(!git(&r.p(), &["log", "--format=%B"]).contains("Reverted-by:"));
}

#[test]
fn a_failure_that_passes_on_rerun_and_on_a_full_check_is_a_flake_and_nothing_is_reverted() {
    for asynchronous in [false, true] {
        flake_on_tip(asynchronous, &["flaky"]);
    }
}

#[test]
fn a_failure_in_two_binaries_that_both_pass_on_rerun_is_a_flake_and_nothing_is_reverted() {
    for asynchronous in [false, true] {
        flake_on_tip(asynchronous, &["flake_a", "flake_b"]);
    }
}

fn whole_revert(r: &Root, entry: &Record, pre: &str) {
    assert!(entry["main_bisect"].starts_with("no verdict:"), "{entry:?}");
    assert_eq!(git(&r.p(), &["rev-parse", "HEAD^"]), entry["main_sha"]);
    assert_eq!(
        git(&r.p(), &["rev-parse", "HEAD^{tree}"]),
        git(&r.p(), &["rev-parse", &format!("{pre}^{{tree}}")])
    );
}

#[test]
fn a_python_or_build_failure_is_no_verdict_and_reverts_the_whole_merge() {
    let build = r#"
fn main() {
    assert!(!env!("CARGO_MANIFEST_DIR").replace('\\', "/").contains("/projects/p"));
}
"#;
    for asynchronous in [false, true] {
        let r = Root::new(asynchronous);
        let pre = git(&r.p(), &["rev-parse", "HEAD"]);
        let (_, a) = r.train_one("src/a.txt", "a\n");
        let (_, b) = r.train_one("build.rs", build);
        r.run(&["queue", "run", "--all"], 6);
        let (a, b) = (r.entry(&a), r.entry(&b));
        assert_eq!(a["status"], "merged_check_failed");
        assert_eq!(a["train"], b["train"]);
        assert_eq!(b["status"], "merged_check_failed");
        whole_revert(&r, &b, &pre);
    }
}

const COUNTER_TEST: &str = r#"
fn count() -> u32 {
    static COUNT: std::sync::OnceLock<u32> = std::sync::OnceLock::new();
    *COUNT.get_or_init(|| {
        let root = root();
        let path = root.join("fails");
        if !path.try_exists().unwrap() { return u32::MAX; }
        let n: u32 = std::fs::read_to_string(&path).unwrap().parse().unwrap();
        if std::env::current_dir().unwrap() == root.join("scratch/projects/p") {
            std::fs::write(path, (n + 1).to_string()).unwrap();
        }
        n
    })
}
#[test] fn flaky() {
    let n = count();
    assert!(n >= LIMIT || (NEW && n != 0));
}
#[test] fn another() {
    let n = count();
    assert!(!NEW || n == 0 || n >= LIMIT);
}
"#;

struct RevertCase {
    root: Root,
    entry: Record,
    green: String,
}

fn revert_case(asynchronous: bool, green_mode: &str, limit: u32, new: bool) -> RevertCase {
    let r = Root::new(asynchronous);
    let pre = git(&r.p(), &["rev-parse", "HEAD"]);
    let test = format!("{ROOT}{COUNTER_TEST}")
        .replace("LIMIT", &limit.to_string())
        .replace("NEW", if new { "true" } else { "false" });
    let (_, a) = r.train_one("tests/flaky.rs", &test);
    r.run(&["queue", "run", "--all"], 0);
    let green = r.entry(&a)["main_sha"].clone();
    let record = r.queue("main-green-p");
    match green_mode {
        "missing" => fs::remove_file(&record).unwrap(),
        "other tree" => fs::write(&record, format!("{pre}\n")).unwrap(),
        "same tree" => {}
        _ => panic!("unexpected green record fixture: {green_mode}"),
    }
    // Worktree reruns still fail while armed but do not advance the main check counter.
    fs::write(r.dir.join("fails"), "0").unwrap();
    let (_, b) = r.train_one("src/c.txt", "c\n");
    r.run(&["queue", "run", "--all"], 6);
    let entry = r.entry(&b);
    println!(
        "async={asynchronous}: green_mode={green_mode}; held={}; reason={}",
        r.queue("hold-p").exists(),
        entry["reason"]
    );
    assert_eq!(entry["status"], "merged_check_failed");
    assert_ne!(entry["revert_sha"], green, "revert is a new commit");
    RevertCase {
        root: r,
        entry,
        green,
    }
}

#[test]
fn a_revert_check_failing_the_same_test_on_a_green_tree_is_a_flake_and_does_not_hold() {
    for asynchronous in [false, true] {
        let RevertCase { root, entry, green } = revert_case(asynchronous, "same tree", 2, false);
        assert!(!root.queue("hold-p").exists(), "{entry:?}");
        assert!(entry["reason"].contains("lane NOT held"));
        let record = fs::read_to_string(root.queue("main-green-p")).unwrap();
        assert_eq!(record.trim_end(), green);
        assert_eq!(entry["flake"], "flaky");
        assert_eq!(
            entry["revert_check"],
            format!("passed (green tree {})", &green[..10])
        );
        let candidates = fs::read_to_string(root.queue("flake-candidates-p")).unwrap();
        assert_eq!(candidates.lines().count(), 1, "{candidates}");
        let prefix = format!("p --test flaky flaky # candidate from {} ", entry["id"]);
        assert!(candidates.starts_with(&prefix));
        assert_eq!(root.checks(), 3, "green, merge failure and post-revert failure");
    }
}

#[test]
fn a_revert_check_that_passes_on_its_re_run_does_not_hold() {
    for asynchronous in [false, true] {
        let RevertCase { root, entry, .. } = revert_case(asynchronous, "missing", 2, false);
        assert!(!root.queue("hold-p").exists(), "{entry:?}");
        assert_eq!(entry["revert_check"], "passed");
        assert!(entry["revert_flake"].starts_with("pass:"));
        assert_eq!(root.checks(), 4);
    }
}

#[test]
fn a_revert_check_failing_on_a_tree_without_a_green_record_still_holds() {
    for asynchronous in [false, true] {
        for green_mode in ["missing", "other tree"] {
            assert_held(revert_case(asynchronous, green_mode, 3, false));
        }
    }
}

fn assert_held(case: RevertCase) {
    let RevertCase { root, entry, .. } = case;
    assert!(root.queue("hold-p").is_file(), "{entry:?}");
    assert!(entry.get("flake").is_none_or(String::is_empty), "{entry:?}");
    assert!(!root.queue("flake-candidates-p").exists());
    assert_eq!(root.checks(), 4, "the fallback full check also failed");
}

#[test]
fn a_revert_check_failing_a_new_test_still_holds() {
    for asynchronous in [false, true] {
        assert_held(revert_case(asynchronous, "same tree", 3, true));
    }
}

#[test]
fn a_rerun_whose_test_holds_the_pipe_is_no_verdict_and_does_not_stall() {
    let pipe = r#"
#[test]
fn always_fails() {
    let root = root();
    if std::env::current_dir().unwrap() != root.join("scratch/projects/p") {
        let mut cmd = if cfg!(windows) {
            let mut c = std::process::Command::new("ping");
            c.args(["-n", "301", "127.0.0.1"]);
            c
        } else {
            let mut c = std::process::Command::new("sleep");
            c.arg("300");
            c
        };
        let child = cmd.stdin(std::process::Stdio::null()).spawn().unwrap();
        std::fs::write(root.join("pid"), child.id().to_string()).unwrap();
    }
    panic!("deliberate failure");
}
"#;
    let test = format!("{ROOT}{pipe}");
    for asynchronous in [false, true] {
        let r = Root::new(asynchronous);
        let pre = git(&r.p(), &["rev-parse", "HEAD"]);
        let (_, entry) = r.train_one("tests/full.rs", &test);
        let start = Instant::now();
        r.run(&["queue", "run", "--all"], 6);
        let elapsed = start.elapsed();
        assert!(r.kill_orphan(), "the re-run must have started a still-live pipe holder");
        let entry = r.entry(&entry);
        println!("async={asynchronous}: elapsed={elapsed:?}; verdict={}", entry["main_bisect"]);
        assert!(elapsed < Duration::from_secs(240), "{elapsed:?}");
        assert!(entry["main_bisect"].contains("TRUNCATED"), "{entry:?}");
        whole_revert(&r, &entry, &pre);
    }
}
