//! Real queue checks of scratch repositories. Helpers are local copies of queue_postcheck.

use std::collections::BTreeMap;
use std::fs;
use std::path::{Path, PathBuf};
use std::process::{Command, Stdio};
use std::sync::atomic::{AtomicUsize, Ordering};
use std::time::{Duration, Instant};

mod support;

static COUNTER: AtomicUsize = AtomicUsize::new(0);
const COUNT: &str = r#"
fn count(name: &str) -> u64 {
    let cwd = std::env::current_dir().unwrap();
    let root = cwd.ancestors()
        .find(|p| p.join("broadsword.toml").is_file())
        .expect("isolated fixture root");
    let path = root.join("scratch").join(format!("{name}.count"));
    let n = match std::fs::read_to_string(&path) {
        Ok(s) => s.parse::<u64>().unwrap(),
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => 0,
        Err(e) => panic!("cannot read counter: {e}"),
    };
    std::fs::write(path, (n + 1).to_string()).unwrap();
    n
}
"#;
const FLAKY: &str = "#[test]\nfn flaky_even() { assert_eq!(count(\"flaky_even\") % 2, 1); }\n";
const ALWAYS: &str = "#[test]\nfn always_fails() { count(\"always_fails\"); panic!(\"always fails\"); }\n";
const PLAIN: &str = "#[test]\nfn plain_fails() { panic!(\"unlisted failure\"); }\n";
const NOTE: &str = "flaky rerun of --lib: flaky_even FAILED then ok";

struct Out {
    code: i32,
    stdout: String,
    stderr: String,
}

fn git(dir: &Path, args: &[&str]) -> String {
    let o = Command::new("git")
        .args(args)
        .current_dir(dir)
        .env("GIT_AUTHOR_NAME", "t")
        .env("GIT_AUTHOR_EMAIL", "t@localhost")
        .env("GIT_COMMITTER_NAME", "t")
        .env("GIT_COMMITTER_EMAIL", "t@localhost")
        .stdin(Stdio::null())
        .output()
        .unwrap();
    assert!(o.status.success(), "git {args:?}: {}", String::from_utf8_lossy(&o.stderr));
    String::from_utf8(o.stdout).unwrap().trim().to_string()
}

fn init_repo(p: &Path) {
    git(p, &["init", "-q", "-b", "main"]);
    for (k, v) in [
        ("user.name", "t"),
        ("user.email", "t@localhost"),
        ("core.autocrlf", "false"),
        ("commit.gpgsign", "false"),
    ] {
        git(p, &["config", k, v]);
    }
}

fn init_project(p: &Path) {
    fs::create_dir_all(p.join("src")).unwrap();
    fs::write(
        p.join("Cargo.toml"),
        "[package]\nname = \"p\"\nversion = \"0.0.0\"\nedition = \"2021\"\n\n[workspace]\n",
    ).unwrap();
    fs::write(
        p.join("Cargo.lock"),
        "# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 3\n\n[[package]]\nname = \"p\"\nversion = \"0.0.0\"\n",
    ).unwrap();
    fs::write(p.join(".gitignore"), "target\n").unwrap();
    fs::write(p.join("src/lib.rs"), "#[test]\nfn smoke() {}\n").unwrap();
    init_repo(p);
    git(p, &["add", "."]);
    git(p, &["commit", "-q", "-m", "first"]);
}

struct Root {
    dir: PathBuf,
    fake: PathBuf,
}

impl Root {
    fn new(tag: &str, list: Option<&str>, asynchronous: bool) -> Self {
        let n = COUNTER.fetch_add(1, Ordering::SeqCst);
        let dir = Path::new(env!("CARGO_MANIFEST_DIR"))
            .join("../../scratch")
            .join(format!("queue-flake-{tag}-{}-{n}", std::process::id()));
        fs::create_dir_all(dir.join("scratch")).unwrap();
        let dir = fs::canonicalize(dir).unwrap();
        let dir = PathBuf::from(dir.to_string_lossy().trim_start_matches(r"\\?\"));
        fs::create_dir_all(dir.join("state/perf")).unwrap();
        init_project(&dir.join("scratch/projects/p"));
        fs::write(
            dir.join("broadsword.toml"),
            support::config(&[
                ("projects_dir", "\"scratch/projects\""),
                ("flaky_tests_file", "\"flaky_tests.txt\""),
                ("merge_train_max", if asynchronous { "4" } else { "1" }),
                ("queue_main_check_async", if asynchronous { "\"on\"" } else { "\"off\"" }),
                ("build_lock_wait_seconds", "600"),
                ("mcp_call_timeout_seconds", "600"),
                ("reviewer_timeout_seconds", "30"),
            ]),
        ).unwrap();
        // Commit only the authority file: task/project and working config changes cannot
        // change the root trunk's allow-list.
        init_repo(&dir);
        let file = if let Some(text) = list {
            fs::write(dir.join("flaky_tests.txt"), text).unwrap();
            "flaky_tests.txt"
        } else {
            fs::write(dir.join("placeholder"), "").unwrap();
            "placeholder"
        };
        git(&dir, &["add", file]);
        git(&dir, &["commit", "-q", "-m", "committed flake authority"]);
        let fake = dir.join("scratch/reviewer").join(Path::new(support::fake_claude()).file_name().unwrap());
        fs::create_dir_all(fake.parent().unwrap()).unwrap();
        fs::copy(support::fake_claude(), &fake).unwrap();
        Self { dir, fake }
    }

    fn p(&self) -> PathBuf {
        self.dir.join("scratch/projects/p")
    }

    fn wt(&self, task: &str) -> PathBuf {
        self.dir.join("worktrees/p").join(task)
    }

    fn run(&self, args: &[&str]) -> Out {
        let n = COUNTER.fetch_add(1, Ordering::SeqCst);
        let out = self.dir.join(format!("scratch/command-{n}.out"));
        let err = self.dir.join(format!("scratch/command-{n}.err"));
        let mut child = Command::new(support::bin())
            .args(args)
            .current_dir(&self.dir)
            .env("BROADSWORD_REVIEWER_CLI", &self.fake)
            .env("FAKE_CLAUDE_OUT_DIR", self.dir.join("fake-out"))
            .env("FAKE_CLAUDE_MODEL", "auto")
            .stdin(Stdio::null())
            .stdout(fs::File::create(&out).unwrap())
            .stderr(fs::File::create(&err).unwrap())
            .spawn()
            .unwrap();
        // Same loaded-machine ceiling as queue_postcheck; passing runs do not wait it out.
        let end = Instant::now() + Duration::from_secs(600 * 5);
        let status = loop {
            if let Some(status) = child.try_wait().unwrap() {
                break status;
            }
            if Instant::now() >= end {
                if cfg!(windows) {
                    let _ = Command::new("taskkill")
                        .args(["/T", "/F", "/PID", &child.id().to_string()])
                        .stdout(Stdio::null())
                        .stderr(Stdio::null())
                        .status();
                }
                let _ = child.kill();
                let _ = child.wait();
                panic!("timed out: {args:?}\n{}\n{}", fs::read_to_string(out).unwrap(), fs::read_to_string(err).unwrap());
            }
            std::thread::sleep(Duration::from_millis(50));
        };
        Out {
            code: status.code().unwrap(),
            stdout: fs::read_to_string(out).unwrap(),
            stderr: fs::read_to_string(err).unwrap(),
        }
    }

    fn ok(&self, args: &[&str]) -> String {
        let o = self.run(args);
        assert_eq!(o.code, 0, "{args:?}\n{}{}", o.stdout, o.stderr);
        o.stdout
    }

    fn commit(&self, dir: &Path, file: &str, text: &str, subject: &str) {
        fs::create_dir_all(dir.join(file).parent().unwrap()).unwrap();
        fs::write(dir.join(file), text).unwrap();
        git(dir, &["add", file]);
        git(dir, &["commit", "-q", "-m", subject]);
    }

    fn entry(&self, id: &str) -> Record {
        record(&self.dir.join("state/queue").join(format!("{id}.entry")))
    }

    fn count(&self, name: &str) -> u64 {
        fs::read_to_string(self.dir.join("scratch").join(format!("{name}.count"))).unwrap().parse().unwrap()
    }
}

impl Drop for Root {
    fn drop(&mut self) {
        let _ = fs::remove_dir_all(&self.dir);
    }
}

type Record = BTreeMap<String, String>;

fn record(path: &Path) -> Record {
    fs::read_to_string(path).unwrap().lines().map(|l| {
        let (k, v) = l.split_once(" = ").or_else(|| l.strip_suffix(" =").map(|k| (k, ""))).expect("record field");
        let mut chars = v.chars();
        let mut value = String::new();
        while let Some(c) = chars.next() {
            value.push(if c == '\\' {
                match chars.next() {
                    Some('n') => '\n',
                    Some('r') => '\r',
                    Some(c) => c,
                    None => '\\',
                }
            } else {
                c
            });
        }
        (k.to_string(), value)
    }).collect()
}

fn train_one(r: &Root) -> (String, String) {
    let file = "src/change.txt";
    let task = r.ok(&["task", "add", "p", "--title", file, "--claim", file]).trim().to_string();
    r.ok(&["task", "start", &task, "--owner", "coder", "--worktree"]);
    r.commit(&r.wt(&task), file, "change\n", "task: change");
    let entry = r.ok(&["queue", "add", &task, "--risk", "low", "--coder", "sonnet"])
        .lines().next().unwrap().trim().to_string();
    (task, entry)
}

fn jobs(r: &Root) -> Vec<Record> {
    let mut jobs: Vec<_> = fs::read_dir(r.dir.join("state/jobs")).unwrap()
        .map(|e| e.unwrap().path())
        .filter(|p| p.extension().is_some_and(|x| x == "rec"))
        .map(|p| record(&p)).collect();
    jobs.sort_by_key(|j| (j["started"].parse::<u64>().unwrap(), j["id"].clone()));
    jobs
}

fn prepare(r: &Root, tests: &str) {
    r.commit(&r.p(), "src/lib.rs", &format!("{COUNT}{tests}"), "install counted tests");
}

fn drain(r: &Root, entry: &str, passed: bool) -> Record {
    let o = r.run(&["queue", "run", "--all"]);
    assert_eq!(o.code, if passed { 0 } else { 5 }, "{}{}", o.stdout, o.stderr);
    let e = r.entry(entry);
    assert_eq!(e["status"], if passed { "merged" } else { "check_failed" }, "{e:?}");
    e
}

#[test]
fn a_listed_flake_reruns_in_the_entry_check_and_in_the_main_check() {
    let r = Root::new("both", Some("p --lib flaky_even\n"), false);
    prepare(&r, FLAKY);
    let (_, entry) = train_one(&r);
    let e = drain(&r, &entry, true);
    assert_eq!(r.count("flaky_even"), 4);
    assert!(e["check_summary"].contains(NOTE), "{e:?}");
    assert!(e["log"].lines().any(|l| l.contains("main_check:") && l.contains(NOTE)), "{e:?}");
    let checks: Vec<_> = jobs(&r).into_iter().filter(|j| j["kind"] == "check").collect();
    assert_eq!(checks.len(), 2);
    assert!(checks.iter().all(|j| j.get("flaky_rerun").is_some_and(|s| s == NOTE)), "{checks:?}");
}

#[test]
fn a_listed_test_that_fails_twice_fails_the_check() {
    let r = Root::new("twice", Some("p --lib always_fails\n"), false);
    prepare(&r, ALWAYS);
    let (_, entry) = train_one(&r);
    let e = drain(&r, &entry, false);
    assert_eq!(r.count("always_fails"), 2);
    assert!(e["check_summary"].contains("flaky rerun of --lib: always_fails FAILED then FAILED again"), "{e:?}");
    // A failed first rerun must not suppress the other failed name's one rerun.
    let r = Root::new("batch", Some("p --lib always_fails\np --lib other_fails\n"), false);
    prepare(&r, &format!("{ALWAYS}\n#[test]\nfn other_fails() {{ count(\"other_fails\"); panic!(\"other failure\"); }}\n"));
    let (_, entry) = train_one(&r);
    let e = drain(&r, &entry, false);
    assert_eq!(r.count("always_fails"), 2);
    assert_eq!(r.count("other_fails"), 2);
    for name in ["always_fails", "other_fails"] {
        assert!(e["check_summary"].contains(&format!("{name} FAILED then FAILED again")), "{e:?}");
    }
}

#[test]
fn an_unlisted_failure_beside_a_listed_one_never_reruns() {
    let r = Root::new("unlisted", Some("p --lib flaky_even\n"), false);
    prepare(&r, &format!("{FLAKY}{PLAIN}"));
    let (_, entry) = train_one(&r);
    let e = drain(&r, &entry, false);
    assert_eq!(r.count("flaky_even"), 1);
    assert!(e["check_summary"].contains("flaky rerun: none (unlisted failure: --lib plain_fails)"), "{e:?}");
    // The side-by-side executor never reruns, even when the sole failure is listed.
    let r = Root::new("parallel", Some("p --lib flaky_even\n"), false);
    let path = r.dir.join("broadsword.toml");
    let text = fs::read_to_string(&path).unwrap();
    assert!(text.contains("test_parallel_binaries = 1"));
    fs::write(path, text.replace("test_parallel_binaries = 1", "test_parallel_binaries = 2")).unwrap();
    prepare(&r, FLAKY);
    let (_, entry) = train_one(&r);
    let e = drain(&r, &entry, false);
    assert_eq!(r.count("flaky_even"), 1);
    assert!(e["check_summary"].contains("flaky rerun: none (test_parallel_binaries is above 1)"), "{e:?}");
}

#[test]
fn after_a_passing_rerun_the_rest_of_the_suite_still_runs() {
    let r = Root::new("later", Some("p --lib flaky_even\n"), false);
    prepare(&r, FLAKY);
    r.commit(&r.p(), "tests/later.rs", "#[test]\nfn later_fails() { panic!(\"later failure\"); }\n", "later executable");
    let (_, entry) = train_one(&r);
    let e = drain(&r, &entry, false);
    assert!(e["check_summary"].contains(NOTE) && e["check_summary"].contains("test: FAILED"), "{e:?}");
    let check = jobs(&r).into_iter().find(|j| j["kind"] == "check").unwrap();
    let log = fs::read_to_string(r.dir.join(&check["log"])).unwrap();
    assert!(log.contains("test later_fails ... FAILED"), "{log}");
    assert_eq!(r.count("flaky_even"), 2);
    // Even a listed failure in a later executable gets no second batch.
    let r = Root::new("one-batch", Some("p --lib flaky_even\np --lib nonexistent\np --test absent missing\np --test later always_fails\n"), false);
    prepare(&r, FLAKY);
    r.commit(&r.p(), "tests/later.rs", &format!("{COUNT}{ALWAYS}"), "listed later executable");
    let (_, entry) = train_one(&r);
    let e = drain(&r, &entry, false);
    assert_eq!(r.count("flaky_even"), 2);
    assert_eq!(r.count("always_fails"), 1);
    assert!(e["check_summary"].contains(NOTE), "{e:?}");
    assert!(e["check_summary"].contains("flaky rerun: none (one rerun already used in this check)"), "{e:?}");
    let check = jobs(&r).into_iter().find(|j| j["kind"] == "check").unwrap();
    let unmatched = &check["flaky_unmatched"];
    let log = fs::read_to_string(r.dir.join(&check["log"])).unwrap();
    for line in [
        "flaky list: p --lib nonexistent matches no test of --lib (ignored)",
        "flaky list: p --test absent missing matches no test of --test absent (ignored)",
    ] {
        assert!(unmatched.split("; ").any(|s| s == line), "{unmatched}");
        assert!(log.contains(line), "{log}");
    }
}

#[test]
fn a_missing_or_empty_list_changes_nothing() {
    for (tag, list) in [("missing", None), ("empty", Some("")), ("invalid", Some("p --lib flaky_even\ninvalid\n"))] {
        let r = Root::new(tag, list, false);
        prepare(&r, FLAKY);
        let (_, entry) = train_one(&r);
        let e = drain(&r, &entry, false);
        assert!(!e["check_summary"].contains("flaky"), "{e:?}");
        assert_eq!(r.count("flaky_even"), 1);
        assert!(jobs(&r).iter().all(|j| !j.contains_key("flaky_rerun") && !j.contains_key("flaky_unmatched")));
    }
}

#[test]
fn an_uncommitted_list_edit_is_not_read() {
    let r = Root::new("working", Some(""), false);
    fs::write(r.dir.join("flaky_tests.txt"), "p --lib flaky_even\n").unwrap();
    prepare(&r, FLAKY);
    let (_, entry) = train_one(&r);
    let e = drain(&r, &entry, false);
    assert!(!e["check_summary"].contains("flaky rerun"), "{e:?}");
    assert_eq!(r.count("flaky_even"), 1);
}

#[test]
fn a_train_check_and_its_async_main_check_rerun_a_listed_flake() {
    let r = Root::new("async", Some("p --lib flaky_even\n"), true);
    prepare(&r, FLAKY);
    let (_, entry) = train_one(&r);
    let o = r.run(&["queue", "run", "--all"]);
    assert_eq!(o.code, 0, "{}{}", o.stdout, o.stderr);
    assert!(o.stdout.contains("runs in the background"), "{}", o.stdout);
    let e = r.entry(&entry);
    assert_eq!(e["status"], "merged", "{e:?}");
    assert_eq!(r.count("flaky_even"), 4);
    let all = jobs(&r);
    let train = all.iter().find(|j| j["id"] == e["train_job"]).expect("train check record");
    let main = all.iter().find(|j| j["kind"] == "check" && j["source"].replace('\\', "/") == "scratch/projects/p").expect("main check record");
    assert_eq!(train["flaky_rerun"], NOTE);
    assert_eq!(main["flaky_rerun"], NOTE);
    assert_ne!(train["id"], main["id"]);
}
