//! Queue-run preconditions against isolated repos, using only the child's real PATH.

use std::collections::BTreeMap;
use std::ffi::OsStr;
use std::fs;
use std::path::{Path, PathBuf};
use std::process::{Command, Stdio};
use std::sync::atomic::{AtomicUsize, Ordering};
use std::time::{Duration, Instant};

mod support;

static COUNTER: AtomicUsize = AtomicUsize::new(0);

#[derive(Debug)]
struct Out {
    code: i32,
    stdout: String,
    stderr: String,
}

struct Root {
    dir: PathBuf,
    empty: PathBuf,
}

impl Root {
    fn new(tag: &str) -> Self {
        let n = COUNTER.fetch_add(1, Ordering::SeqCst);
        let dir = Path::new(env!("CARGO_MANIFEST_DIR"))
            .join("../../scratch")
            .join(format!("queue-bash-{tag}-{}-{n}", std::process::id()));
        fs::create_dir_all(dir.join("scratch/empty-path")).unwrap();
        let dir = fs::canonicalize(dir).unwrap();
        let dir = PathBuf::from(dir.to_string_lossy().trim_start_matches(r"\\?\"));
        let r = Self {
            empty: dir.join("scratch/empty-path"),
            dir,
        };
        r.configure("\"p\"", "\"on\"", "1");
        let p = r.dir.join("scratch/projects/p");
        fs::create_dir_all(p.join("src")).unwrap();
        fs::write(
            p.join("Cargo.toml"),
            "[package]\nname = \"p\"\nversion = \"0.0.0\"\nedition = \"2021\"\n\n[workspace]\n",
        )
        .unwrap();
        fs::write(
            p.join("Cargo.lock"),
            "# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 3\n\n[[package]]\nname = \"p\"\nversion = \"0.0.0\"\n",
        )
        .unwrap();
        fs::write(p.join("src/lib.rs"), "pub fn p() {}\n").unwrap();
        r.git(&p, &["init", "-q", "-b", "main"]);
        for (key, value) in [
            ("user.name", "t"),
            ("user.email", "t@localhost"),
            ("core.autocrlf", "false"),
            ("commit.gpgsign", "false"),
        ] {
            r.git(&p, &["config", key, value]);
        }
        r.git(&p, &["add", "."]);
        r.git(&p, &["commit", "-q", "-m", "first"]);
        r
    }

    fn configure(&self, projects: &str, per_project: &str, train: &str) {
        fs::write(
            self.dir.join("broadsword.toml"),
            support::config(&[
                ("projects_dir", "\"scratch/projects\""),
                ("bash_projects", projects),
                ("queue_per_project", per_project),
                ("merge_train_max", train),
            ]),
        )
        .unwrap();
    }

    fn command(&self, mut command: Command) -> Out {
        // File-backed output keeps a failed guard from filling pipes before the bounded wait.
        let n = COUNTER.fetch_add(1, Ordering::SeqCst);
        let out = self.dir.join(format!("scratch/command-{n}.out"));
        let err = self.dir.join(format!("scratch/command-{n}.err"));
        let mut child = command
            .stdin(Stdio::null())
            .stdout(fs::File::create(&out).unwrap())
            .stderr(fs::File::create(&err).unwrap())
            .spawn()
            .unwrap();
        let config = fs::read_to_string(self.dir.join("broadsword.toml")).unwrap();
        let timeout = config
            .lines()
            .find_map(|line| line.strip_prefix("done_check_timeout_seconds = "))
            .expect("fixture command timeout")
            .parse::<u64>()
            .unwrap();
        let end = Instant::now() + Duration::from_secs(timeout);
        let status = loop {
            if let Some(status) = child.try_wait().unwrap() {
                break status;
            }
            if Instant::now() >= end {
                child.kill().unwrap();
                child.wait().unwrap();
                panic!("command timed out: {command:?}");
            }
            std::thread::sleep(Duration::from_millis(20));
        };
        Out {
            code: status.code().expect("command exited without a code"),
            stdout: fs::read_to_string(out).unwrap(),
            stderr: fs::read_to_string(err).unwrap(),
        }
    }

    fn git(&self, dir: &Path, args: &[&str]) {
        let mut command = Command::new("git");
        command
            .args(args)
            .current_dir(dir)
            .env("GIT_AUTHOR_NAME", "t")
            .env("GIT_AUTHOR_EMAIL", "t@localhost")
            .env("GIT_COMMITTER_NAME", "t")
            .env("GIT_COMMITTER_EMAIL", "t@localhost");
        let out = self.command(command);
        assert_eq!(out.code, 0, "git {args:?}: {out:?}");
    }

    fn run(&self, args: &[&str], path: Option<&OsStr>) -> Out {
        let mut command = Command::new(support::bin());
        command.args(args).current_dir(&self.dir);
        if let Some(path) = path {
            // Only the queue run under test gets a synthetic PATH; setup uses the normal PATH.
            assert_eq!(&args[..2], &["queue", "run"]);
            command.env("PATH", path);
        }
        self.command(command)
    }

    fn ok(&self, args: &[&str]) -> String {
        let out = self.run(args, None);
        assert_eq!(out.code, 0, "{args:?}: {out:?}");
        out.stdout
    }

    fn queued(&self) -> String {
        let task = self
            .ok(&["task", "add", "p", "--title", "bash gate", "--claim", "src/a.txt"])
            .trim()
            .to_string();
        assert!(!task.is_empty(), "task add returned no id");
        self.ok(&["task", "start", &task, "--owner", "coder", "--worktree"]);
        let wt = self.dir.join("worktrees/p").join(&task);
        fs::write(wt.join("src/a.txt"), "a\n").unwrap();
        self.git(&wt, &["add", "src/a.txt"]);
        self.git(&wt, &["commit", "-q", "-m", "task"]);
        let entry = self
            .ok(&["queue", "add", &task, "--risk", "low", "--coder", "sonnet"])
            .lines()
            .next()
            .expect("queue add returned no id")
            .trim()
            .to_string();
        assert!(!entry.is_empty(), "queue add returned an empty id");
        assert!(self.dir.join(format!("state/queue/{entry}.entry")).is_file());
        entry
    }

    fn refused(&self, args: &[&str], path: &OsStr, reason: &str) {
        let queue = snapshot(&self.dir.join("state/queue"));
        let jobs = snapshot(&self.dir.join("state/jobs"));
        let out = self.run(args, Some(path));
        assert_eq!(out.code, 2, "{args:?}: {out:?}");
        for text in ["bash not on PATH", "project `p`", "nothing was run", reason] {
            assert!(out.stderr.contains(text), "missing {text:?}: {out:?}");
        }
        // Includes entry bytes, existing locks and any newly-created lock or hold file.
        assert_eq!(snapshot(&self.dir.join("state/queue")), queue);
        assert_eq!(snapshot(&self.dir.join("state/jobs")), jobs);
    }
}

fn snapshot(dir: &Path) -> BTreeMap<PathBuf, Vec<u8>> {
    let entries = match fs::read_dir(dir) {
        Ok(entries) => entries,
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => return BTreeMap::new(),
        Err(e) => panic!("cannot snapshot {}: {e}", dir.display()),
    };
    let mut files = BTreeMap::new();
    for entry in entries {
        let path = entry.unwrap().path();
        if path.is_dir() {
            files.extend(snapshot(&path));
        } else {
            files.insert(path.clone(), fs::read(&path).unwrap());
        }
    }
    files
}

#[test]
fn a_bash_project_lane_is_refused_without_bash() {
    let r = Root::new("missing");
    let entry = r.queued();
    for train in ["1", "4"] {
        r.configure("\"p\"", "\"on\"", train);
        for args in [
            vec!["queue", "run", "--project", "p"],
            vec!["queue", "run", "--all", "--project", "p"],
            vec!["queue", "run", "--entry", &entry],
        ] {
            r.refused(&args, r.empty.as_os_str(), "no bash or bash.exe");
        }
    }
    r.configure("\"p\"", "\"off\"", "1");
    r.refused(
        &["queue", "run", "--entry", &entry],
        r.empty.as_os_str(),
        "no bash or bash.exe",
    );
    // An unkeyed run can touch any configured bash project, even before choosing an entry.
    r.refused(&["queue", "run"], r.empty.as_os_str(), "no bash or bash.exe");
    r.refused(
        &["queue", "run", "--all"],
        r.empty.as_os_str(),
        "no bash or bash.exe",
    );
    let out = r.run(
        &["queue", "run", "--entry", "t-20261126-115112"],
        Some(r.empty.as_os_str()),
    );
    assert_eq!(out.code, 2, "{out:?}");
    assert!(out.stderr.contains("no queue entry"), "{out:?}");
    assert!(!out.stderr.contains("bash not on PATH"), "{out:?}");
}

#[test]
fn a_bash_that_does_not_run_is_refused() {
    let r = Root::new("broken");
    r.queued();
    let fake = r.dir.join("scratch/broken-path");
    fs::create_dir(&fake).unwrap();
    let bash = fake.join(if cfg!(windows) { "bash.exe" } else { "bash" });
    fs::write(&bash, "not a program").unwrap();
    let path = std::env::join_paths([&r.empty, &fake]).unwrap();
    r.refused(&["queue", "run", "--project", "p"], &path, "was found but");
    // This executable really starts but rejects -c: nonzero exit rather than spawn failure.
    fs::copy(support::bin(), &bash).unwrap();
    r.refused(&["queue", "run", "--project", "p"], &path, "failed: exit");
    // A later working bash must not hide the first PATH match's failure; relative folders work too.
    let mut folders = vec![r.empty.clone(), PathBuf::from("scratch/broken-path")];
    folders.extend(std::env::split_paths(&std::env::var_os("PATH").unwrap()));
    let path = std::env::join_paths(folders).unwrap();
    r.refused(&["queue", "run", "--project", "p"], &path, "failed: exit");
}

#[test]
fn a_lane_without_bash_steps_is_not_refused() {
    let r = Root::new("unlisted");
    for projects in ["\"other\"", "\"\""] {
        r.configure(projects, "\"on\"", "1");
        let out = r.run(
            &["queue", "run", "--project", "p"],
            Some(r.empty.as_os_str()),
        );
        assert_eq!(out.code, 0, "{out:?}");
        assert!(out.stdout.contains("the queue is empty"), "{out:?}");
        assert!(!out.stderr.contains("bash not on PATH"), "{out:?}");
    }
}

#[test]
fn a_bash_project_runs_when_bash_runs() {
    let r = Root::new("working");
    r.refused(
        &["queue", "run", "--project", "p"],
        r.empty.as_os_str(),
        "no bash or bash.exe",
    );
    for projects in ["\"p\"", "\"P\"", "\"a.A_0-9  \tp\""] {
        r.configure(projects, "\"on\"", "1");
        r.refused(
            &["queue", "run", "--project", "p"],
            r.empty.as_os_str(),
            "no bash or bash.exe",
        );
        let out = r.run(&["queue", "run", "--project", "p"], None);
        assert_eq!(
            out.code, 0,
            "this test needs Git for Windows' bash on PATH: {out:?}"
        );
        assert!(out.stdout.contains("the queue is empty"), "{out:?}");
        assert!(!out.stderr.contains("bash not on PATH"), "{out:?}");
    }
}

#[test]
fn bash_projects_is_required_and_validated() {
    let r = Root::new("config");
    fs::write(
        r.dir.join("broadsword.toml"),
        support::config_without("bash_projects"),
    )
    .unwrap();
    let out = r.run(&["status"], None);
    assert_eq!(out.code, 1, "{out:?}");
    assert!(
        out.stderr.contains("bash_projects") && out.stderr.contains("missing"),
        "{out:?}"
    );
    for projects in ["\"p q/r\"", "\"p C:\\bash\"", "\"p q;other\"", "\"p q#r\""] {
        r.configure(projects, "\"on\"", "1");
        let out = r.run(&["status"], None);
        assert_eq!(out.code, 1, "{projects}: {out:?}");
        assert!(out.stderr.contains("bash_projects"), "{projects}: {out:?}");
    }
    // Validation must reach an invalid name even after a large valid prefix.
    let projects = format!("\"{}q/r\"", "p ".repeat(16_384));
    r.configure(&projects, "\"on\"", "1");
    let out = r.run(&["status"], None);
    assert_eq!(out.code, 1, "{out:?}");
    assert!(out.stderr.contains("bash_projects"), "{out:?}");
}
