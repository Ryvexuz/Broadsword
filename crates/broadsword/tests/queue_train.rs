//! End-to-end tests for the reviewer step and merge queue (`broadsword queue ...`): the real binary, REAL Git repos and a real
//! (tiny) cargo project, inside throwaway Broadsword roots under the repo's `scratch/` folder. The project `p` of each root is
//! its own Git repo under `projects/`; the real Broadsword repo and the crash sim are never touched.
//!
//! NO MODEL IS EVER CALLED and there is no network: the reviewer CLI is `fake_claude` (tests/support/fake_claude.rs), COPIED into
//! the throwaway root's `scratch/reviewer/` (the only place inside a root an override may point at: the TEST HOOK), which
//! `BROADSWORD_REVIEWER_CLI` names. It records what it was given, so the tests can assert that it received the diff and the check
//! output, and that its environment was scrubbed.

use std::fs;

use std::path::{Path, PathBuf};
use std::process::{Child, Command, Stdio};
use std::sync::atomic::{AtomicUsize, Ordering};
use std::time::{Duration, Instant};

mod support;
use support::{bin, fake_claude};
static COUNTER: AtomicUsize = AtomicUsize::new(0);

const LIB_BASE: &str = "pub fn add(a: i32, b: i32) -> i32 {\n    a + b\n}\n\n#[cfg(test)]\nmod tests {\n    #[test]\n    fn adds() {\n        assert_eq!(super::add(1, 2), 3);\n    }\n}\n";

struct Out {
    code: i32,
    stdout: String,
    stderr: String,
}

fn git_out(dir: &Path, args: &[&str]) -> Out {
    let o = Command::new("git")
        .args(args)
        .current_dir(dir)
        .env("GIT_AUTHOR_NAME", "t")
        .env("GIT_AUTHOR_EMAIL", "t@localhost")
        .env("GIT_COMMITTER_NAME", "t")
        .env("GIT_COMMITTER_EMAIL", "t@localhost")
        .stdin(Stdio::null())
        .output()
        .unwrap();
    Out { code: o.status.code().unwrap(), stdout: String::from_utf8_lossy(&o.stdout).into_owned(), stderr: String::from_utf8_lossy(&o.stderr).into_owned() }
}

fn git(dir: &Path, args: &[&str]) -> String {
    let o = git_out(dir, args);
    assert_eq!(o.code, 0, "git {args:?} in {} failed: {}", dir.display(), o.stderr);
    o.stdout.trim().to_string()
}

/// A tiny cargo project `name` at `p`, a Git repo on `main` with one commit.
fn init_project(p: &Path, name: &str) {
    fs::create_dir_all(p.join("src")).unwrap();
    fs::write(p.join("Cargo.toml"), format!("[package]\nname = \"{name}\"\nversion = \"0.0.0\"\nedition = \"2021\"\n\n[workspace]\n")).unwrap();
    fs::write(p.join("Cargo.lock"), format!("# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 3\n\n[[package]]\nname = \"{name}\"\nversion = \"0.0.0\"\n")).unwrap();
    fs::write(p.join(".gitignore"), "target\n").unwrap();
    fs::write(p.join("src/lib.rs"), LIB_BASE).unwrap();
    git(p, &["init", "-q", "-b", "main"]);
    for (k, v) in [("user.name", "t"), ("user.email", "t@localhost"), ("core.autocrlf", "false"), ("commit.gpgsign", "false")] {
        git(p, &["config", k, v]);
    }
    git(p, &["add", "."]);
    git(p, &["commit", "-q", "-m", "first"]);
}

struct Root {
    dir: PathBuf,
    fake_out: PathBuf,
    /// The fake reviewer, copied into this root's scratch folder.
    fake: PathBuf,
    /// The projects folder, relative to the root. Fixtures live INSIDE scratch_dir (a stand-in reviewer may merge only there).
    projects: &'static str,
}

impl Root {
    /// `timeout_s` is the reviewer_timeout_seconds setting.
    fn new(name: &str, timeout_s: u64) -> Root {
        Root::with_projects(name, timeout_s, "scratch/projects")
    }

    fn with_projects(name: &str, timeout_s: u64, projects: &'static str) -> Root {
        Root::build(name, timeout_s, projects, "off", 5)
    }

    fn build(name: &str, timeout_s: u64, projects: &'static str, shadow: &str, shadow_timeout_s: u64) -> Root {
        let n = COUNTER.fetch_add(1, Ordering::SeqCst);
        let dir = Path::new(env!("CARGO_MANIFEST_DIR")).join("../../scratch").join(format!("qu-{name}-{}-{n}", std::process::id()));
        let _ = fs::remove_dir_all(&dir);
        fs::create_dir_all(dir.join("scratch")).unwrap();
        let dir = fs::canonicalize(&dir).unwrap();
        let dir = PathBuf::from(dir.to_string_lossy().trim_start_matches(r"\\?\"));
        init_project(&dir.join(projects).join("p"), "p");
        let toml = support::config(&[("projects_dir", &format!("\"{projects}\"")), ("mcp_call_timeout_seconds", "600"), ("build_lock_wait_seconds", "60"), ("reviewer_timeout_seconds", &timeout_s.to_string()), ("shadow_reviewer", &format!("\"{shadow}\"")), ("shadow_reviewer_timeout_seconds", &shadow_timeout_s.to_string())]);
        fs::write(dir.join("broadsword.toml"), toml).unwrap();
        let fake_out = dir.join("fake-out");
        let fake = dir.join("scratch/reviewer").join(Path::new(fake_claude()).file_name().unwrap());
        fs::create_dir_all(fake.parent().unwrap()).unwrap();
        fs::copy(fake_claude(), &fake).unwrap();
        Root { dir, fake_out, fake, projects }
    }

    fn p(&self) -> PathBuf {
        self.dir.join(self.projects).join("p")
    }

    fn wt(&self, id: &str) -> PathBuf {
        self.dir.join("worktrees/p").join(id)
    }

    fn command(&self, args: &[&str], env: &[(&str, &str)]) -> Command {
        let mut c = Command::new(bin());
        c.args(args).current_dir(&self.dir).stdin(Stdio::null()).env("BROADSWORD_REVIEWER_CLI", &self.fake).env("FAKE_CLAUDE_OUT_DIR", &self.fake_out).env("FAKE_CLAUDE_MODEL", "auto");
        for (k, v) in env {
            c.env(k, v);
        }
        c
    }

    fn run(&self, args: &[&str]) -> Out {
        self.run_env(args, &[])
    }

    fn run_env(&self, args: &[&str], env: &[(&str, &str)]) -> Out {
        let o = self.command(args, env).output().unwrap();
        Out { code: o.status.code().unwrap(), stdout: String::from_utf8_lossy(&o.stdout).into_owned(), stderr: String::from_utf8_lossy(&o.stderr).into_owned() }
    }

    fn spawn(&self, args: &[&str], env: &[(&str, &str)]) -> Child {
        self.command(args, env).stdout(Stdio::null()).stderr(Stdio::null()).spawn().unwrap()
    }

    /// A task in `p` with its own claim, started with a worktree.
    fn started(&self, claim: &str) -> String {
        self.started_in("p", claim)
    }

    /// A task in `project` (`p`, or one made by `init_project` in the projects folder) with its own claim, started with a worktree.
    fn started_in(&self, project: &str, claim: &str) -> String {
        let o = self.run(&["task", "add", project, "--title", &format!("make {project} better"), "--claim", claim]);
        assert_eq!(o.code, 0, "{}", o.stderr);
        let id = o.stdout.trim().to_string();
        let o = self.run(&["task", "start", &id, "--owner", "coder", "--worktree"]);
        assert_eq!(o.code, 0, "{}{}", o.stdout, o.stderr);
        id
    }

    /// Write `content` to `file` in `dir` and commit it there. Returns the new commit.
    fn commit(&self, dir: &Path, file: &str, content: &str, msg: &str) -> String {
        if let Some(parent) = Path::new(file).parent() {
            fs::create_dir_all(dir.join(parent)).unwrap();
        }
        fs::write(dir.join(file), content).unwrap();
        git(dir, &["add", file]);
        git(dir, &["commit", "-q", "-m", msg]);
        git(dir, &["rev-parse", "HEAD"])
    }

    /// `queue add`, asserting success; returns the entry id.
    fn add(&self, task: &str, risk: &str, coder: &str) -> String {
        let o = self.run(&["queue", "add", task, "--risk", risk, "--coder", coder]);
        assert_eq!(o.code, 0, "queue add: {}{}", o.stdout, o.stderr);
        o.stdout.lines().next().unwrap().trim().to_string()
    }

    fn show(&self, entry: &str) -> String {
        let o = self.run(&["queue", "show", entry]);
        assert_eq!(o.code, 0, "{}", o.stderr);
        o.stdout
    }

    fn field(&self, entry: &str, key: &str) -> String {
        self.show(entry).lines().find_map(|l| l.strip_prefix(&format!("{key}: "))).unwrap_or("").to_string()
    }

    fn status(&self, entry: &str) -> String {
        self.field(entry, "status")
    }

    fn task_status(&self, id: &str) -> String {
        let o = self.run(&["task", "show", id]);
        assert_eq!(o.code, 0, "{}", o.stderr);
        o.stdout.lines().find_map(|l| l.strip_prefix("status: ")).unwrap_or("").to_string()
    }

    /// How many times the fake reviewer was started.
    fn calls(&self) -> usize {
        fs::read_to_string(self.fake_out.join("calls.log")).map(|t| t.lines().count()).unwrap_or(0)
    }

    fn branch_tip(&self, id: &str) -> String {
        git(&self.p(), &["rev-parse", &format!("task/{id}")])
    }

    fn head(&self) -> String {
        git(&self.p(), &["rev-parse", "HEAD"])
    }

}

impl Drop for Root {
    fn drop(&mut self) {
        let _ = fs::remove_dir_all(&self.dir);
    }
}

/// Kill a process and everything it started (the reviewer child too).
fn kill_tree(c: &mut Child) {
    if cfg!(windows) {
        let _ = Command::new("taskkill").args(["/T", "/F", "/PID", &c.id().to_string()]).stdout(Stdio::null()).stderr(Stdio::null()).status();
    }
    let _ = c.kill();
    let _ = c.wait();
}

/// Every wait ceiling in this file is multiplied by this. At 97-100% CPU the unchanged code failed only here, on ceilings of 60 to 240 s
/// (scratch/logs/jobs/20261120-183343-broadsword-check.log: 6 failed; scratch/main-recheck-748bd33.txt: 83 passed, 9 failed in 632.50 s).
/// A passing test returns as soon as its condition is true, so this costs nothing on a pass; a real hang still fails, only later.
const WAIT_CEILING_FACTOR: u64 = 5;

/// A wait ceiling of `secs` seconds, scaled by `WAIT_CEILING_FACTOR`.
fn ceiling(secs: u64) -> Duration {
    Duration::from_secs(secs * WAIT_CEILING_FACTOR)
}

fn wait_for(what: &str, secs: u64, mut ok: impl FnMut() -> bool) {
    let end = Instant::now() + ceiling(secs);
    while !ok() {
        assert!(Instant::now() < end, "timed out waiting for {what}");
        std::thread::sleep(Duration::from_millis(50));
    }
}


