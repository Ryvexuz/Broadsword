//! Real fast-subset queue checks in isolated scratch repos, with Python and no real reviewer.
//! Fixture helpers are local copies of queue_postcheck's model.

use std::collections::BTreeMap;
use std::fs;
use std::path::{Path, PathBuf};
use std::process::{Command, Stdio};
use std::sync::atomic::{AtomicUsize, Ordering};
use std::time::{Duration, Instant};

mod support;

static COUNTER: AtomicUsize = AtomicUsize::new(0);
const CARGO: &str = "cargo build --offline && cargo test --offline --lib --test smoke";
const PYTHON: &str = "python -I -B scripts/test_m.py";
const TEST_M: &str = r#"import importlib.util
from pathlib import Path
import sys

spec = importlib.util.spec_from_file_location("m", Path(__file__).with_name("m.py"))
m = importlib.util.module_from_spec(spec)
spec.loader.exec_module(m)
sys.exit(0 if m.v() == 1 else 1)
"#;

struct Out {
    code: i32,
    stdout: String,
    stderr: String,
}

// File-backed capture keeps a child (or a descendant holding its pipes) from blocking capture.
// The wait ceiling comes from this fixture's required timeout setting.
fn capture(root: &Path, command: &mut Command) -> Out {
    let timeout = fs::read_to_string(root.join("broadsword.toml"))
        .unwrap()
        .lines()
        .find_map(|line| line.strip_prefix("mcp_call_timeout_seconds = "))
        .expect("fixture timeout setting")
        .parse::<u64>()
        .expect("positive integer fixture timeout");
    assert!(timeout > 0, "fixture timeout must be positive");
    let n = COUNTER.fetch_add(1, Ordering::SeqCst);
    let out = root.join(format!("scratch/command-{n}.out"));
    let err = root.join(format!("scratch/command-{n}.err"));
    let mut child = command
        .stdin(Stdio::null())
        .stdout(fs::File::create(&out).unwrap())
        .stderr(fs::File::create(&err).unwrap())
        .spawn()
        .unwrap();
    let end = Instant::now() + Duration::from_secs(timeout);
    let status = loop {
        if let Some(status) = child.try_wait().unwrap() {
            break status;
        }
        if Instant::now() >= end {
            if cfg!(windows) {
                let _ = Command::new("taskkill")
                    .args(["/T", "/F", "/PID", &child.id().to_string()])
                    .stdout(Stdio::null())
                    .stderr(Stdio::null())
                    .status();
            }
            let _ = child.kill();
            let _ = child.wait();
            panic!(
                "timed out: {command:?}\n{}{}",
                fs::read_to_string(out).unwrap(),
                fs::read_to_string(err).unwrap()
            );
        }
        std::thread::sleep(Duration::from_millis(50));
    };
    Out {
        code: status.code().unwrap(),
        stdout: fs::read_to_string(out).unwrap(),
        stderr: fs::read_to_string(err).unwrap(),
    }
}

fn git(dir: &Path, args: &[&str]) -> String {
    let root = dir
        .ancestors()
        .find(|p| p.join("broadsword.toml").is_file())
        .expect("git runs only inside this fixture root");
    let o = capture(
        root,
        Command::new("git")
            .args(args)
            .current_dir(dir)
            .env("GIT_AUTHOR_NAME", "t")
            .env("GIT_AUTHOR_EMAIL", "t@localhost")
            .env("GIT_COMMITTER_NAME", "t")
            .env("GIT_COMMITTER_EMAIL", "t@localhost"),
    );
    assert_eq!(o.code, 0, "git {args:?}: {}{}", o.stdout, o.stderr);
    o.stdout.trim().to_string()
}

fn init_project(p: &Path) {
    for folder in ["src", "tests", "scripts"] {
        fs::create_dir_all(p.join(folder)).unwrap();
    }
    fs::write(
        p.join("Cargo.toml"),
        "[package]\nname = \"p\"\nversion = \"0.0.0\"\nedition = \"2021\"\n\n[workspace]\n",
    )
    .unwrap();
    fs::write(
        p.join("Cargo.lock"),
        "# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 3\n\n[[package]]\nname = \"p\"\nversion = \"0.0.0\"\n",
    )
    .unwrap();
    fs::write(p.join(".gitignore"), "target\n").unwrap();
    fs::write(p.join("src/lib.rs"), "pub fn v() -> u8 { 1 }\n").unwrap();
    fs::write(p.join("tests/smoke.rs"), "#[test]\nfn smoke() {}\n").unwrap();
    fs::write(p.join("scripts/m.py"), "def v(): return 1\n").unwrap();
    fs::write(p.join("scripts/test_m.py"), TEST_M).unwrap();
    git(p, &["init", "-q", "-b", "main"]);
    for (key, value) in [
        ("user.name", "t"),
        ("user.email", "t@localhost"),
        ("core.autocrlf", "false"),
        ("commit.gpgsign", "false"),
    ] {
        git(p, &["config", key, value]);
    }
    git(p, &["add", "."]);
    git(p, &["commit", "-q", "-m", "first"]);
}

struct Root {
    dir: PathBuf,
    fake: PathBuf,
}

impl Root {
    fn new(tag: &str) -> Self {
        let n = COUNTER.fetch_add(1, Ordering::SeqCst);
        let dir = Path::new(env!("CARGO_MANIFEST_DIR"))
            .join("../../scratch")
            .join(format!("train-python-{tag}-{}-{n}", std::process::id()));
        fs::create_dir_all(dir.join("scratch")).unwrap();
        let dir = fs::canonicalize(dir).unwrap();
        let dir = PathBuf::from(dir.to_string_lossy().trim_start_matches(r"\\?\"));
        fs::write(
            dir.join("broadsword.toml"),
            support::config(&[
                ("projects_dir", "\"scratch/projects\""),
                ("merge_fast_tests", "\"p: smoke\""),
                ("queue_auto_revert", "\"on\""),
                ("merge_train_max", "4"),
                ("merge_train_lanes", "1"),
                ("python_tests", "\"p: scripts/test_m.py\""),
                ("queue_main_check_async", "\"off\""),
                ("build_lock_wait_seconds", "600"),
                ("mcp_call_timeout_seconds", "600"),
                ("reviewer_timeout_seconds", "30"),
            ]),
        )
        .unwrap();
        init_project(&dir.join("scratch/projects/p"));
        let fake = dir
            .join("scratch/reviewer")
            .join(Path::new(support::fake_claude()).file_name().unwrap());
        fs::create_dir_all(fake.parent().unwrap()).unwrap();
        fs::copy(support::fake_claude(), &fake).unwrap();
        Self { dir, fake }
    }

    fn p(&self) -> PathBuf {
        self.dir.join("scratch/projects/p")
    }

    fn wt(&self, task: &str) -> PathBuf {
        self.dir.join("worktrees/p").join(task)
    }

    fn run(&self, args: &[&str]) -> Out {
        capture(
            &self.dir,
            Command::new(support::bin())
                .args(args)
                .current_dir(&self.dir)
                .env("BROADSWORD_REVIEWER_CLI", &self.fake)
                .env("FAKE_CLAUDE_OUT_DIR", self.dir.join("fake-out"))
                .env("FAKE_CLAUDE_MODEL", "auto"),
        )
    }

    fn ok(&self, args: &[&str]) -> String {
        let o = self.run(args);
        assert_eq!(o.code, 0, "{args:?}\n{}{}", o.stdout, o.stderr);
        o.stdout
    }

    fn entry(&self, id: &str) -> Record {
        record(&self.dir.join("state/queue").join(format!("{id}.entry")))
    }
}

impl Drop for Root {
    fn drop(&mut self) {
        // Keep scratch evidence when an assertion fails.
        if !std::thread::panicking() {
            let _ = fs::remove_dir_all(&self.dir);
        }
    }
}

type Record = BTreeMap<String, String>;

fn record(path: &Path) -> Record {
    fs::read_to_string(path)
        .unwrap()
        .lines()
        .map(|line| {
            let (key, value) = line
                .split_once(" = ")
                .or_else(|| line.strip_suffix(" =").map(|key| (key, "")))
                .expect("record field");
            let mut chars = value.chars();
            let mut value = String::new();
            while let Some(c) = chars.next() {
                value.push(if c == '\\' {
                    match chars.next() {
                        Some('n') => '\n',
                        Some('r') => '\r',
                        Some(c) => c,
                        None => '\\',
                    }
                } else {
                    c
                });
            }
            (key.to_string(), value)
        })
        .collect()
}

fn set(path: &Path, key: &str, value: &str) {
    let text = fs::read_to_string(path).unwrap();
    assert!(
        text.lines()
            .any(|l| l.split_once(" = ").is_some_and(|(k, _)| k == key)),
        "fixture lacks {key}"
    );
    fs::write(
        path,
        text.lines()
            .map(|line| {
                if line.split_once(" = ").is_some_and(|(k, _)| k == key) {
                    format!("{key} = {value}\n")
                } else {
                    format!("{line}\n")
                }
            })
            .collect::<String>(),
    )
    .unwrap();
}

// Extra edits happen before queue add, so the entry is queued with its final commit and claims.
fn train_one(r: &Root, file: &str, edits: &[(&str, Option<&str>)]) -> (String, String) {
    let task = r
        .ok(&["task", "add", "p", "--title", file, "--claim", file])
        .trim()
        .to_string();
    r.ok(&["task", "start", &task, "--owner", "coder", "--worktree"]);
    let wt = r.wt(&task);
    fs::write(wt.join(file), format!("{file}\n")).unwrap();
    for (path, contents) in edits {
        match contents {
            Some(contents) => fs::write(wt.join(path), contents).unwrap(),
            None => fs::remove_file(wt.join(path)).unwrap(),
        }
    }
    let claims = std::iter::once(file)
        .chain(edits.iter().map(|(path, _)| *path))
        .collect::<Vec<_>>()
        .join("\\n");
    set(
        &r.dir.join("state/tasks").join(format!("{task}.task")),
        "claims",
        &claims,
    );
    git(&wt, &["add", "-A"]);
    git(&wt, &["commit", "-q", "-m", &format!("task: {file}")]);
    let entry = r
        .ok(&["queue", "add", &task, "--risk", "low", "--coder", "sonnet"])
        .lines()
        .next()
        .unwrap()
        .trim()
        .to_string();
    (task, entry)
}

fn jobs(r: &Root) -> Vec<Record> {
    let mut jobs: Vec<_> = fs::read_dir(r.dir.join("state/jobs"))
        .unwrap()
        .map(|entry| entry.unwrap().path())
        .filter(|path| path.extension().is_some_and(|ext| ext == "rec"))
        .map(|path| record(&path))
        .collect();
    jobs.sort_by_key(|job| (job["started"].parse::<u64>().unwrap(), job["id"].clone()));
    jobs
}

#[test]
fn a_train_whose_python_test_fails_is_rejected_before_any_merge() {
    let r = Root::new("reject");
    let (a_task, a) = train_one(&r, "src/a.txt", &[("scripts/m.py", Some("def v(): return 2\n"))]);
    let a_commit = git(&r.wt(&a_task), &["rev-parse", "HEAD"]);
    let (b_task, b) = train_one(&r, "src/b.txt", &[]);
    let o = r.run(&["queue", "run", "--all"]);
    assert_eq!(o.code, 5, "{}{}", o.stdout, o.stderr);
    let (a, b) = (r.entry(&a), r.entry(&b));
    assert_eq!(a["status"], "check_failed", "{a:?}");
    assert_eq!(a["check_exit"], "1", "{a:?}");
    assert!(
        a["check_summary"].contains("+ python (1 of 1 script(s), touched by this diff)"),
        "{a:?}"
    );
    assert!(a["check_summary"].contains("run: FAILED"), "{a:?}");
    assert_eq!(b["status"], "merged", "{b:?}");
    assert!(
        o.stdout.contains("all 2 entries combined") && o.stdout.contains("bisect:"),
        "the rejection must come from a combined train and its bisect\n{}{}",
        o.stdout,
        o.stderr
    );
    let log = git(&r.p(), &["log", "--format=%H%n%B"]);
    assert!(!log.contains("Reverted-by"), "{log}");
    assert!(!log.contains(&a_commit), "{log}");
    assert!(!r.p().join("src/a.txt").exists());
    assert_eq!(
        fs::read_to_string(r.p().join("scripts/m.py")).unwrap(),
        "def v(): return 1\n"
    );
    let all = jobs(&r);
    let failed_tip = all
        .iter()
        .find(|job| job["kind"] == "run" && job["task"] == b_task && job["status"] == "failed")
        .expect("the combined tip's run job must fail on Python");
    assert_eq!(failed_tip["command"], format!("{CARGO} && {PYTHON}"));
    let failed_prefix = all
        .iter()
        .find(|job| job["id"] == a["check_job"])
        .expect("the culprit's bisect/own check job");
    assert_eq!(failed_prefix["status"], "failed");
    assert_eq!(failed_prefix["command"], format!("{CARGO} && {PYTHON}"));
    // A is first, so the bisect of its prefix is also its alone check (train.rs).
    // The explicit single-entry route must classify the same Python failure normally too.
    let single = Root::new("single-reject");
    let (_, entry) = train_one(
        &single,
        "src/a.txt",
        &[("scripts/m.py", Some("def v(): return 2\n"))],
    );
    let head = git(&single.p(), &["rev-parse", "HEAD"]);
    let o = single.run(&["queue", "run", "--entry", &entry]);
    assert_eq!(o.code, 5, "{}{}", o.stdout, o.stderr);
    let e = single.entry(&entry);
    assert_eq!(e["status"], "check_failed", "{e:?}");
    assert!(e["check_summary"].contains("run: FAILED"), "{e:?}");
    assert!(e["check_summary"].contains("+ python (1 of 1"), "{e:?}");
    assert_eq!(git(&single.p(), &["rev-parse", "HEAD"]), head);
}

#[test]
fn a_train_with_no_python_change_runs_no_python() {
    let r = Root::new("cargo-only");
    let (_, entry) = train_one(&r, "src/a.txt", &[]);
    let o = r.run(&["queue", "run", "--all"]);
    assert_eq!(o.code, 0, "{}{}", o.stdout, o.stderr);
    let e = r.entry(&entry);
    assert_eq!(e["status"], "merged", "{e:?}");
    assert!(
        e["check_summary"].contains(&format!("check: fast subset (smoke) = `{CARGO}`")),
        "{e:?}"
    );
    assert!(!e["check_summary"].contains("+ python"), "{e:?}");
    let all = jobs(&r);
    let runs: Vec<_> = all
        .iter()
        .filter(|job| job["project"] == "p" && job["kind"] == "run")
        .collect();
    assert!(!runs.is_empty(), "the pre-merge run must exist: {all:?}");
    for job in runs {
        assert_eq!(job["command"], CARGO, "{job:?}");
        assert!(!job["command"].contains("python"), "{job:?}");
    }
    assert!(
        all.iter().any(|job| job["kind"] == "check"
            && job["task"].is_empty()
            && job["command"].contains(PYTHON)
            && job["status"] == "done"),
        "the full main check still runs the configured Python suite: {all:?}"
    );
}

#[test]
fn a_deleted_test_script_is_not_run() {
    let r = Root::new("deleted");
    let (_, entry) = train_one(&r, "src/a.txt", &[("scripts/test_m.py", None)]);
    // The declared missing script can fail the full main check; judge only the pre-merge job.
    let o = r.run(&["queue", "run", "--all"]);
    let e = r.entry(&entry);
    assert_eq!(e["check_exit"], "0", "{}{}\n{e:?}", o.stdout, o.stderr);
    assert!(
        e["check_summary"].contains(&format!("check: fast subset (smoke) = `{CARGO}`")),
        "{e:?}"
    );
    assert!(!e["check_summary"].contains("+ python"), "{e:?}");
    let all = jobs(&r);
    let pre_merge = all
        .iter()
        .find(|job| job["id"] == e["check_job"])
        .expect("the pre-merge job must exist even if the main check failed");
    assert_eq!(pre_merge["kind"], "run", "{pre_merge:?}");
    assert_eq!(pre_merge["status"], "done", "{pre_merge:?}");
    assert_eq!(pre_merge["command"], CARGO, "{pre_merge:?}");
    assert!(!pre_merge["command"].contains("python"), "{pre_merge:?}");
}
