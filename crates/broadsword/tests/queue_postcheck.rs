//! Real train merges against isolated scratch repos; no network or real reviewer.
//! Helpers are local copies of the queue_train fixture, not changes to its shared lane.

use std::collections::BTreeMap;
use std::fs;
use std::path::{Path, PathBuf};
use std::process::{Command, Stdio};
use std::sync::atomic::{AtomicUsize, Ordering};
use std::time::{Duration, Instant};

mod support;

static COUNTER: AtomicUsize = AtomicUsize::new(0);
const LIB: &str = "#[test]\nfn takes_four_seconds() {\n    std::thread::sleep(std::time::Duration::from_secs(4));\n}\n";
const BARRIER_LIB: &str = r#"
#[test]
fn controlled_main_check() {
    use std::{fs, thread, time::{Duration, Instant}};
    let cwd = std::env::current_dir().unwrap();
    let root = cwd.ancestors()
        .find(|p| p.join("broadsword.toml").is_file())
        .expect("isolated fixture root");
    let gate = root.join("scratch/postcheck-barrier");
    let exe = std::env::current_exe().unwrap();
    let job = exe.parent().unwrap().file_name().unwrap().to_str().unwrap();
    if cwd == root.join("scratch/projects/p") {
        match fs::OpenOptions::new().write(true).create_new(true)
            .open(gate.join("main-started"))
        {
            Ok(_) => {
                fs::write(gate.join("first-job"), job).unwrap();
                let end = Instant::now() + Duration::from_secs(120);
                while !gate.join("release").try_exists().unwrap() {
                    assert!(Instant::now() < end,
                        "overlap barrier timed out after 120 s: second train check did not start while first main check was held");
                    thread::sleep(Duration::from_millis(50));
                }
                fs::write(gate.join("main-ended"), "").unwrap();
            }
            Err(e) if e.kind() == std::io::ErrorKind::AlreadyExists => {}
            Err(e) => panic!("cannot create main-check barrier: {e}"),
        }
    } else if cwd.join("src/b.txt").is_file() && cwd.join("src/a.txt").is_file()
    {
        // Only the second train's rebased tip has both files. Its entry check has just b.
        // Either job may reach its tests first; wait without holding the build lock.
        let end = Instant::now() + Duration::from_secs(120);
        while !gate.join("main-started").try_exists().unwrap() {
            assert!(Instant::now() < end,
                "overlap barrier timed out after 120 s: first main check never reached its tests");
            thread::sleep(Duration::from_millis(50));
        }
        fs::write(gate.join("second-job"), job).unwrap();
        fs::write(gate.join("second-order"),
            if gate.join("main-ended").try_exists().unwrap() { "after" } else { "overlap" }
        ).unwrap();
    }
}
"#;

struct Out {
    code: i32,
    stdout: String,
    stderr: String,
}

fn git(dir: &Path, args: &[&str]) -> String {
    let o = Command::new("git")
        .args(args)
        .current_dir(dir)
        .env("GIT_AUTHOR_NAME", "t")
        .env("GIT_AUTHOR_EMAIL", "t@localhost")
        .env("GIT_COMMITTER_NAME", "t")
        .env("GIT_COMMITTER_EMAIL", "t@localhost")
        .stdin(Stdio::null())
        .output()
        .unwrap();
    assert!(
        o.status.success(),
        "git {args:?}: {}",
        String::from_utf8_lossy(&o.stderr)
    );
    String::from_utf8(o.stdout).unwrap().trim().to_string()
}

fn init_project(p: &Path) {
    fs::create_dir_all(p.join("src")).unwrap();
    fs::write(
        p.join("Cargo.toml"),
        "[package]\nname = \"p\"\nversion = \"0.0.0\"\nedition = \"2021\"\n\n[workspace]\n",
    )
    .unwrap();
    fs::write(
        p.join("Cargo.lock"),
        "# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 3\n\n[[package]]\nname = \"p\"\nversion = \"0.0.0\"\n",
    )
    .unwrap();
    fs::write(p.join(".gitignore"), "target\n").unwrap();
    fs::write(p.join("src/lib.rs"), LIB).unwrap();
    git(p, &["init", "-q", "-b", "main"]);
    for (k, v) in [
        ("user.name", "t"),
        ("user.email", "t@localhost"),
        ("core.autocrlf", "false"),
        ("commit.gpgsign", "false"),
    ] {
        git(p, &["config", k, v]);
    }
    git(p, &["add", "."]);
    git(p, &["commit", "-q", "-m", "first"]);
}

struct Root {
    dir: PathBuf,
    fake: PathBuf,
}

impl Root {
    fn new(tag: &str, asynchronous: bool) -> Self {
        let n = COUNTER.fetch_add(1, Ordering::SeqCst);
        let dir = Path::new(env!("CARGO_MANIFEST_DIR"))
            .join("../../scratch")
            .join(format!("postcheck-{tag}-{}-{n}", std::process::id()));
        fs::create_dir_all(dir.join("scratch")).unwrap();
        let dir = fs::canonicalize(dir).unwrap();
        let dir = PathBuf::from(dir.to_string_lossy().trim_start_matches(r"\\?\"));
        // Async requires a checkable baseline location, not just a missing baseline file.
        fs::create_dir_all(dir.join("state/perf")).unwrap();
        init_project(&dir.join("scratch/projects/p"));
        fs::write(
            dir.join("broadsword.toml"),
            support::config(&[
                ("projects_dir", "\"scratch/projects\""),
                ("merge_train_max", "4"),
                (
                    "queue_main_check_async",
                    if asynchronous { "\"on\"" } else { "\"off\"" },
                ),
                ("build_lock_wait_seconds", "600"),
                ("mcp_call_timeout_seconds", "600"),
                ("reviewer_timeout_seconds", "30"),
            ]),
        )
        .unwrap();
        let fake = dir
            .join("scratch/reviewer")
            .join(Path::new(support::fake_claude()).file_name().unwrap());
        fs::create_dir_all(fake.parent().unwrap()).unwrap();
        fs::copy(support::fake_claude(), &fake).unwrap();
        Self { dir, fake }
    }

    fn p(&self) -> PathBuf {
        self.dir.join("scratch/projects/p")
    }

    fn wt(&self, task: &str) -> PathBuf {
        self.dir.join("worktrees/p").join(task)
    }

    fn run(&self, args: &[&str]) -> Out {
        self.run_observing(args, || {})
    }

    fn run_observing(&self, args: &[&str], mut observe: impl FnMut()) -> Out {
        // Files avoid filling a pipe while the parent enforces a bounded wait.
        let n = COUNTER.fetch_add(1, Ordering::SeqCst);
        let out = self.dir.join(format!("scratch/command-{n}.out"));
        let err = self.dir.join(format!("scratch/command-{n}.err"));
        let mut child = Command::new(support::bin())
            .args(args)
            .current_dir(&self.dir)
            .env("BROADSWORD_REVIEWER_CLI", &self.fake)
            .env("FAKE_CLAUDE_OUT_DIR", self.dir.join("fake-out"))
            .env("FAKE_CLAUDE_MODEL", "auto")
            .stdin(Stdio::null())
            .stdout(fs::File::create(&out).unwrap())
            .stderr(fs::File::create(&err).unwrap())
            .spawn()
            .unwrap();
        let end = Instant::now() + ceiling(600);
        let status = loop {
            observe();
            if let Some(status) = child.try_wait().unwrap() {
                break status;
            }
            if Instant::now() >= end {
                if cfg!(windows) {
                    let _ = Command::new("taskkill")
                        .args(["/T", "/F", "/PID", &child.id().to_string()])
                        .stdout(Stdio::null())
                        .stderr(Stdio::null())
                        .status();
                }
                let _ = child.kill();
                let _ = child.wait();
                panic!(
                    "timed out: {args:?}\n{}\n{}",
                    fs::read_to_string(out).unwrap(),
                    fs::read_to_string(err).unwrap()
                );
            }
            std::thread::sleep(Duration::from_millis(50));
        };
        Out {
            code: status.code().unwrap(),
            stdout: fs::read_to_string(out).unwrap(),
            stderr: fs::read_to_string(err).unwrap(),
        }
    }

    fn ok(&self, args: &[&str]) -> String {
        let o = self.run(args);
        assert_eq!(o.code, 0, "{args:?}\n{}{}", o.stdout, o.stderr);
        o.stdout
    }

    fn commit(&self, dir: &Path, file: &str, contents: &str, subject: &str) {
        fs::create_dir_all(dir.join(file).parent().unwrap()).unwrap();
        fs::write(dir.join(file), contents).unwrap();
        git(dir, &["add", file]);
        git(dir, &["commit", "-q", "-m", subject]);
    }

    fn entry(&self, id: &str) -> Record {
        record(&self.dir.join("state/queue").join(format!("{id}.entry")))
    }
}

impl Drop for Root {
    fn drop(&mut self) {
        let _ = fs::remove_dir_all(&self.dir);
    }
}

// Same loaded-machine ceiling as queue_train; passing runs do not wait out the ceiling.
fn ceiling(secs: u64) -> Duration {
    Duration::from_secs(secs * 5)
}

type Record = BTreeMap<String, String>;

fn record(path: &Path) -> Record {
    fs::read_to_string(path)
        .unwrap()
        .lines()
        .map(|l| {
            let (k, v) = l
                .split_once(" = ")
                .or_else(|| l.strip_suffix(" =").map(|k| (k, "")))
                .expect("record field");
            // Decode the durable record's escaping, including multi-line logs.
            let mut chars = v.chars();
            let mut value = String::new();
            while let Some(c) = chars.next() {
                value.push(if c == '\\' {
                    match chars.next() {
                        Some('n') => '\n',
                        Some('r') => '\r',
                        Some(c) => c,
                        None => '\\',
                    }
                } else {
                    c
                });
            }
            (k.to_string(), value)
        })
        .collect()
}

fn set(path: &Path, key: &str, value: &str) {
    let text = fs::read_to_string(path).unwrap();
    assert!(
        text.lines()
            .any(|l| l.split_once(" = ").is_some_and(|(k, _)| k == key)),
        "fixture lacks {key}"
    );
    fs::write(
        path,
        text.lines()
            .map(|l| {
                if l.split_once(" = ").is_some_and(|(k, _)| k == key) {
                    format!("{key} = {value}\n")
                } else {
                    format!("{l}\n")
                }
            })
            .collect::<String>(),
    )
    .unwrap();
}

fn train_one(r: &Root, file: &str, contents: &str) -> (String, String) {
    let task = r
        .ok(&["task", "add", "p", "--title", file, "--claim", file])
        .trim()
        .to_string();
    r.ok(&["task", "start", &task, "--owner", "coder", "--worktree"]);
    r.commit(&r.wt(&task), file, contents, &format!("task: {file}"));
    let entry = r
        .ok(&["queue", "add", &task, "--risk", "low", "--coder", "sonnet"])
        .lines()
        .next()
        .unwrap()
        .trim()
        .to_string();
    (task, entry)
}

fn two_trains(r: &Root, first_file: &str, first_contents: &str) -> (String, String) {
    let (_, a) = train_one(r, first_file, first_contents);
    let (b_task, b) = train_one(r, "src/b.txt", "b\n");
    // The board disallows starting overlapping claims. After both starts, plant the overlap
    // exactly as queue_train does, so the train picker must make separate trains.
    set(
        &r.dir.join("state/tasks").join(format!("{b_task}.task")),
        "claims",
        "*",
    );
    (a, b)
}

fn jobs(r: &Root) -> Vec<Record> {
    let mut jobs: Vec<_> = fs::read_dir(r.dir.join("state/jobs"))
        .unwrap()
        .map(|e| e.unwrap().path())
        .filter(|p| p.extension().is_some_and(|x| x == "rec"))
        .map(|p| record(&p))
        .collect();
    jobs.sort_by_key(|j| (number(j, "started"), j["id"].clone()));
    jobs
}

fn number(r: &Record, key: &str) -> u64 {
    r.get(key)
        .unwrap_or_else(|| panic!("missing {key}: {r:?}"))
        .parse()
        .unwrap_or_else(|_| panic!("invalid {key}: {r:?}"))
}

fn main_jobs(r: &Root) -> Vec<Record> {
    jobs(r)
        .into_iter()
        .filter(|j| j["kind"] == "check" && j["source"].replace('\\', "/") == "scratch/projects/p")
        .collect()
}

fn overlap_case(asynchronous: bool) {
    let r = Root::new(
        if asynchronous { "overlap-on" } else { "overlap-off" },
        asynchronous,
    );
    let gate = r.dir.join("scratch/postcheck-barrier");
    fs::create_dir_all(&gate).unwrap();
    r.commit(&r.p(), "src/lib.rs", BARRIER_LIB, "control the main check");
    let (a, b) = two_trains(&r, "src/a.txt", "a\n");
    let mut released = false;
    let o = r.run_observing(&["queue", "run", "--all"], || {
        let ready = if asynchronous {
            fs::read_to_string(gate.join("second-order")).is_ok_and(|s| s == "overlap")
        } else {
            gate.join("main-started").is_file()
        };
        if ready && !released {
            fs::write(gate.join("release"), "").unwrap();
            released = true;
        }
    });
    assert!(
        released,
        "overlap barrier was not released: second train check must start while first main check is held (120 s cap)\n{}{}",
        o.stdout, o.stderr
    );
    assert_eq!(o.code, 0, "{}{}", o.stdout, o.stderr);
    let (a, b) = (r.entry(&a), r.entry(&b));
    assert_eq!(a["status"], "merged", "{a:?}");
    assert_eq!(b["status"], "merged", "{b:?}");
    assert_ne!(a["train"], b["train"], "the overlap must force two trains");
    let main = main_jobs(&r);
    assert_eq!(main.len(), 2, "{}{}", o.stdout, o.stderr);
    let first_job = fs::read_to_string(gate.join("first-job")).unwrap();
    let first = main
        .iter()
        .find(|j| j["id"] == first_job)
        .expect("the held main check's job");
    assert_eq!(first["status"], "done");
    assert!(gate.join("main-ended").is_file());
    let second_job = fs::read_to_string(gate.join("second-job")).unwrap();
    assert_eq!(
        second_job, b["train_job"],
        "the barrier proof must come from the second TRAIN check, not its entry check"
    );
    let order = fs::read_to_string(gate.join("second-order")).unwrap();
    println!("async={asynchronous}: first_main_job={first_job}; second_train_job={second_job}; order={order}; released={released}");
    assert_eq!(order, if asynchronous { "overlap" } else { "after" });
    if asynchronous {
        let settle = o
            .stdout
            .find(&format!("passed (job {first_job})"))
            .expect("first check settlement");
        let forward = o
            .stdout
            .find(&format!("merge train {}: main fast-forwarded", b["train"]))
            .expect("second fast-forward");
        assert!(settle < forward, "second fast-forward must follow settlement");
    } else {
        assert!(!o.stdout.contains("runs in the background"));
    }
}

#[test]
fn async_main_check_overlaps_the_next_train_check() {
    overlap_case(true);
    overlap_case(false);
}

#[test]
fn a_failing_async_main_check_is_reverted_before_the_next_fast_forward() {
    let r = Root::new("revert", true);
    set(&r.dir.join("broadsword.toml"), "queue_auto_revert", "\"on\"");
    set(&r.dir.join("broadsword.toml"), "merge_fast_tests", "\"p: smoke\"");
    r.commit(
        &r.p(),
        "tests/smoke.rs",
        "#[test]\nfn smoke() {}\n",
        "add fast test binary",
    );
    let good = "#[test]\nfn full_only() {\n    std::thread::sleep(std::time::Duration::from_secs(4));\n    assert_eq!(1, 1);\n}\n";
    r.commit(&r.p(), "tests/full.rs", good, "add full-only test binary");
    let (a, b) = two_trains(
        &r,
        "tests/full.rs",
        &good.replace("assert_eq!(1, 1)", "assert_eq!(1, 2)"),
    );
    let o = r.run(&["queue", "run", "--all"]);
    assert_eq!(o.code, 6, "{}{}", o.stdout, o.stderr);
    let (a, b) = (r.entry(&a), r.entry(&b));
    assert_eq!(a["status"], "merged_check_failed", "{a:?}");
    assert_eq!(a["revert_check"], "passed", "{a:?}");
    assert_eq!(b["status"], "stale", "{b:?}");
    assert!(b["reason"].contains("main moved"), "{b:?}");
    assert_eq!(
        git(&r.p(), &["rev-parse", "HEAD^"]),
        a["main_sha"],
        "the revert is one new commit directly on the broken train tip"
    );
    assert!(
        !r.p().join("src/b.txt").exists(),
        "the second train never fast-forwarded"
    );
    assert!(git(&r.p(), &["log", "-1", "--format=%B"]).contains("Reverted-by: broadsword queue"));
    let all = jobs(&r);
    let fast = all.iter().find(|j| j["id"] == a["train_job"]).unwrap();
    assert_eq!(fast["kind"], "run");
    assert_eq!(
        fast["status"], "done",
        "the subset passed; it was the full main check that failed"
    );
    assert!(
        main_jobs(&r).iter().any(|j| j["status"] == "failed"),
        "a real full main check must have failed"
    );
}

#[test]
fn the_drain_never_ends_with_a_pending_main_check() {
    let r = Root::new("last", true);
    let (_, entry) = train_one(&r, "src/a.txt", "a\n");
    let o = r.run(&["queue", "run", "--all"]);
    assert_eq!(o.code, 0, "{}{}", o.stdout, o.stderr);
    let e = r.entry(&entry);
    assert_eq!(
        e["status"], "merged",
        "the drain must settle its last train: {e:?}"
    );
    let main = main_jobs(&r);
    assert_eq!(main.len(), 1, "one full main check");
    assert_eq!(main[0]["status"], "done");
    assert!(number(&main[0], "ended") >= number(&main[0], "started"));
    assert!(o.stdout.contains("runs in the background"), "{}", o.stdout);
    assert!(o.stdout.contains("passed (job "), "{}", o.stdout);
}

#[test]
fn one_async_main_check_finishes_every_member_of_its_train() {
    let r = Root::new("members", true);
    let (_, a) = train_one(&r, "src/a.txt", "a\n");
    let (_, b) = train_one(&r, "src/b.txt", "b\n");
    let o = r.run(&["queue", "run", "--all"]);
    assert_eq!(o.code, 0, "{}{}", o.stdout, o.stderr);
    let (a, b) = (r.entry(&a), r.entry(&b));
    assert_eq!(a["status"], "merged", "{a:?}");
    assert_eq!(b["status"], "merged", "{b:?}");
    assert_eq!(a["train"], b["train"]);
    assert!(a["log"].contains("covered by the one main check"));
    assert!(b["log"].contains("check on main passed"));
    assert_eq!(main_jobs(&r).len(), 1);
}
