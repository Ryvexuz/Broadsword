//! End-to-end tests of the DONE CHECK the merge queue runs itself (src/donecheck.rs, `Run::s_done_check` in src/queue.rs): the
//! real binary, real Git repos and a real tiny cargo project in throwaway Broadsword roots under the repo's `scratch/` folder.
//! The brief's done-check commands are run by the queue's own binary (`broadsword run p --task <id> -- git ...`, `broadsword test
//! p --task <id>`), never a stand-in. NO MODEL IS EVER CALLED: the reviewer is `fake_claude`, as in tests/queue.rs, and it records
//! the prompt it got (`stdin.txt`) and every call (`calls.log`).

use std::fs;
use std::path::{Path, PathBuf};
use std::process::{Command, Stdio};
use std::sync::atomic::{AtomicUsize, Ordering};
use std::time::Instant;

mod support;
use support::{bin, fake_claude};
static COUNTER: AtomicUsize = AtomicUsize::new(0);

const LIB: &str = "pub fn add(a: i32, b: i32) -> i32 {\n    a + b\n}\n\n#[cfg(test)]\nmod tests {\n    #[test]\n    fn adds() {\n        assert_eq!(super::add(1, 2), 3);\n    }\n}\n";

/// A value held by the `queue run` process under a secret name (so the queue redacts it). The child broadsword never gets it
/// (scrubbed environment), so the child cannot redact it itself: only the queue's own redaction stands between it and the file.
const PLANTED_NAME: &str = "BS_DONECHECK_TEST_TOKEN";
const PLANTED: &str = "dc-planted-secret-4e1b9c7a";

struct Out {
    code: i32,
    stdout: String,
    stderr: String,
}

fn git(dir: &Path, args: &[&str]) -> String {
    let o = Command::new("git").args(args).current_dir(dir).stdin(Stdio::null()).output().unwrap();
    assert!(o.status.success(), "git {args:?} in {}: {}", dir.display(), String::from_utf8_lossy(&o.stderr));
    String::from_utf8_lossy(&o.stdout).trim().to_string()
}

struct Root {
    dir: PathBuf,
    fake: PathBuf,
    fake_out: PathBuf,
}

impl Root {
    fn new(name: &str, extra: &[(&str, &str)]) -> Root {
        let n = COUNTER.fetch_add(1, Ordering::SeqCst);
        let dir = Path::new(env!("CARGO_MANIFEST_DIR")).join("../../scratch").join(format!("dc-{name}-{}-{n}", std::process::id()));
        let _ = fs::remove_dir_all(&dir);
        fs::create_dir_all(dir.join("scratch")).unwrap();
        let dir = fs::canonicalize(&dir).unwrap();
        let dir = PathBuf::from(dir.to_string_lossy().trim_start_matches(r"\\?\"));
        let p = dir.join("scratch/projects/p");
        fs::create_dir_all(p.join("src")).unwrap();
        fs::write(p.join("Cargo.toml"), "[package]\nname = \"p\"\nversion = \"0.0.0\"\nedition = \"2021\"\n\n[workspace]\n").unwrap();
        fs::write(p.join("Cargo.lock"), "# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 3\n\n[[package]]\nname = \"p\"\nversion = \"0.0.0\"\n").unwrap();
        fs::write(p.join(".gitignore"), "target\n").unwrap();
        fs::write(p.join("src/lib.rs"), LIB).unwrap();
        git(&p, &["init", "-q", "-b", "main"]);
        for (k, v) in [("user.name", "t"), ("user.email", "t@localhost"), ("core.autocrlf", "false"), ("commit.gpgsign", "false")] {
            git(&p, &["config", k, v]);
        }
        git(&p, &["add", "."]);
        git(&p, &["commit", "-q", "-m", "first"]);
        let mut over: Vec<(&str, &str)> = vec![("projects_dir", "\"scratch/projects\""), ("build_lock_wait_seconds", "60"), ("reviewer_timeout_seconds", "30"), ("done_check_timeout_seconds", "600"), ("done_check_tail_lines", "40")];
        for (k, v) in extra {
            over.retain(|(o, _)| o != k);
            over.push((k, v));
        }
        fs::write(dir.join("broadsword.toml"), support::config(&over)).unwrap();
        let fake_out = dir.join("fake-out");
        let fake = dir.join("scratch/reviewer").join(Path::new(fake_claude()).file_name().unwrap());
        fs::create_dir_all(fake.parent().unwrap()).unwrap();
        fs::copy(fake_claude(), &fake).unwrap();
        Root { dir, fake, fake_out }
    }

    fn run_env(&self, args: &[&str], env: &[(&str, &str)]) -> Out {
        let mut c = Command::new(bin());
        c.args(args).current_dir(&self.dir).stdin(Stdio::null()).env("BROADSWORD_REVIEWER_CLI", &self.fake).env("FAKE_CLAUDE_OUT_DIR", &self.fake_out).env("FAKE_CLAUDE_MODEL", "auto");
        for (k, v) in env {
            c.env(k, v);
        }
        let o = c.output().unwrap();
        Out { code: o.status.code().unwrap(), stdout: String::from_utf8_lossy(&o.stdout).into_owned(), stderr: String::from_utf8_lossy(&o.stderr).into_owned() }
    }

    fn run(&self, args: &[&str]) -> Out {
        self.run_env(args, &[])
    }

    fn wt(&self, id: &str) -> PathBuf {
        self.dir.join("worktrees/p").join(id)
    }

    /// A started task (worktree) that commits `file`, queued with a brief whose Done check section is `done_check`.
    fn queued(&self, file: &str, content: &str, done_check: &str) -> (String, String) {
        let o = self.run(&["task", "add", "p", "--title", "make p better", "--claim", file]);
        assert_eq!(o.code, 0, "{}", o.stderr);
        let id = o.stdout.trim().to_string();
        let o = self.run(&["task", "start", &id, "--owner", "coder", "--worktree"]);
        assert_eq!(o.code, 0, "{}{}", o.stdout, o.stderr);
        let wt = self.wt(&id);
        fs::write(wt.join(file), content).unwrap();
        git(&wt, &["add", file]);
        git(&wt, &["-c", "user.name=t", "-c", "user.email=t@localhost", "commit", "-q", "-m", &format!("task: {file}")]);
        let brief = self.dir.join(format!("brief-{id}.md"));
        fs::write(&brief, format!("# Brief: make p better\n\n**Task:** add {file}.\n\n**Done check (each line is a command and what it must show):**\n{done_check}")).unwrap();
        let o = self.run(&["queue", "add", &id, "--risk", "low", "--coder", "sonnet", "--brief", brief.to_str().unwrap()]);
        assert_eq!(o.code, 0, "queue add: {}{}", o.stdout, o.stderr);
        (id, o.stdout.lines().next().unwrap().trim().to_string())
    }

    fn field(&self, entry: &str, key: &str) -> String {
        let o = self.run(&["queue", "show", entry]);
        assert_eq!(o.code, 0, "{}", o.stderr);
        o.stdout.lines().find_map(|l| l.strip_prefix(&format!("{key}: "))).unwrap_or("").to_string()
    }

    fn show(&self, entry: &str) -> String {
        self.run(&["queue", "show", entry]).stdout
    }

    fn calls(&self) -> usize {
        fs::read_to_string(self.fake_out.join("calls.log")).map(|t| t.lines().count()).unwrap_or(0)
    }

    fn prompt(&self) -> String {
        fs::read_to_string(self.fake_out.join("stdin.txt")).unwrap()
    }

    /// How many job records of `kind` (build, test, check, run) this root has.
    fn jobs_of(&self, kind: &str) -> usize {
        let want = format!("kind = {kind}");
        fs::read_dir(self.dir.join("state/jobs")).into_iter().flatten().flatten().filter(|e| fs::read_to_string(e.path()).unwrap_or_default().lines().any(|l| l == want)).count()
    }

    fn donecheck(&self, entry: &str) -> String {
        let p = self.dir.join("state/queue").join(format!("{entry}.donecheck"));
        fs::read_to_string(&p).unwrap_or_else(|e| panic!("{}: {e}", p.display()))
    }
}

impl Drop for Root {
    fn drop(&mut self) {
        let _ = fs::remove_dir_all(&self.dir);
    }
}

#[test]
fn a_passing_done_check_is_run_by_the_queue_and_the_reviewer_reads_its_output_and_every_not_run_line() {
    let r = Root::new("pass", &[]);
    let (id, e) = r.queued(
        "src/a.txt",
        "x\n",
        "1. `broadsword run p --task <id> -- git rev-parse HEAD` -> the reviewed commit\n2. `python -I scripts/x.py` -> ok\n3. `cargo test` -> ok\n4. `broadsword test p --task <id>` -> `test: ok`\n5. The donecheck file, pasted.\n6. `broadsword check p --task <id>` -> `check: ok`\n7. `broadsword build p --task <id>` -> `build: ok`\n",
    );
    let tip = git(&r.wt(&id), &["rev-parse", "HEAD"]);
    let o = r.run(&["queue", "run", "--entry", &e]);
    assert_eq!(o.code, 0, "{}{}", o.stdout, o.stderr);
    assert_eq!(r.field(&e, "status"), "merged", "reason = {}", r.field(&e, "reason"));
    assert_eq!(r.calls(), 1);
    let file = r.donecheck(&e);
    let prompt = r.prompt();
    for text in [&file, &prompt] {
        assert!(text.contains(&format!("[1] RUN: broadsword run p --task {id} -- git rev-parse HEAD")), "{text}");
        assert!(text.contains(&format!("    {tip}")), "the command's real output (the reviewed commit) is shown: {text}");
        assert!(text.contains("[2] NOT RUN (manual): python -I scripts/x.py") && text.contains("`python` is not the Broadsword binary"), "{text}");
        assert!(text.contains("[3] NOT RUN (manual): cargo test") && text.contains("`cargo` is not the Broadsword binary"), "{text}");
        assert!(text.contains("[4] COVERED by the queue's check (job ") && text.contains(&format!(": broadsword test p --task {id}\n")), "{text}");
        assert!(text.contains("[6] COVERED by the queue's check (job ") && text.contains(&format!(": broadsword check p --task {id}\n")), "{text}");
        assert!(text.contains("-p-check: build: ok") && text.contains("test: ok"), "the COVERED lines carry the queue check's job id and result: {text}");
        assert!(text.contains("[5] NOT RUN (manual): The donecheck file, pasted.") && text.contains("no command in backticks"), "{text}");
        assert!(text.contains(&format!("[7] RUN: broadsword build p --task {id}")) && text.contains("build: ok"), "{text}");
        assert_eq!(text.matches("result: PASS; exit 0").count(), 2, "{text}");
    }
    // the test and check lines started no job: the only check job is the queue's own, and no test job ran at all
    assert_eq!((r.jobs_of("test"), r.jobs_of("check"), r.jobs_of("run"), r.jobs_of("build")), (0, 2, 1, 1), "the queue's check and main check; one run; one build");
    assert!(prompt.contains("DONE CHECK, RUN BY THE QUEUE"), "{prompt}");
    assert!(file.contains(&format!("commit: {tip}")) && file.contains(&format!("entry: {e}")), "{file}");
    assert!(r.show(&e).contains("done check, run by the queue"), "queue show lists it");
}

#[test]
fn a_failing_done_check_command_rejects_the_entry_before_any_review() {
    let r = Root::new("fail", &[]);
    let (_id, e) = r.queued("src/a.txt", "x\n", "1. `broadsword run p --task <id> -- git rev-parse --verify no-such-ref-dc` -> fails\n2. `broadsword build p --task <id>` -> `build: ok`\n");
    let o = r.run(&["queue", "run", "--entry", &e]);
    assert_eq!(o.code, 5, "{}{}", o.stdout, o.stderr);
    assert_eq!(r.field(&e, "status"), "rejected");
    let why = r.field(&e, "reason");
    assert!(why.contains("done-check command [1] of the brief FAILED (exit 128: the job ran and its step FAILED)") && why.contains("No model was asked"), "{why}");
    assert_eq!(r.calls(), 0, "no reviewer was called");
    let file = r.donecheck(&e);
    assert!(file.contains("result: FAIL (exit 128: the job ran and its step FAILED)"), "{file}");
    assert!(file.contains("[2] NOT RUN (an earlier done-check command did not pass)"), "{file}");
    assert_eq!(r.field(&e, "verdict"), "", "no verdict was recorded");
}

