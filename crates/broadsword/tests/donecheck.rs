#[test]
fn a_train_members_test_and_check_lines_are_covered_pending_and_never_run() {
    let r = Root::new("trainok", &[("merge_train_max", "2")]);
    let (id, e) = r.queued("src/a.txt", "x\n", "1. `broadsword test p --task <id>` -> `test: ok`\n2. `broadsword check p --task <id>` -> ok\n3. `broadsword run p --task <id> -- git rev-parse HEAD` -> the commit\n");
    let o = r.run(&["queue", "run", "--all"]);
    assert_eq!(o.code, 0, "{}{}", o.stdout, o.stderr);
    assert_eq!(r.field(&e, "status"), "merged", "reason = {}", r.field(&e, "reason"));
    let prompt = r.prompt();
    for n in [1, 2] {
        assert!(prompt.contains(&format!("[{n}] COVERED (pending: the merge train's check of the combined branches decides; nothing merges unless it passes)")), "{prompt}");
    }
    assert!(prompt.contains(&format!("[3] RUN: broadsword run p --task {id} -- git rev-parse HEAD")) && prompt.contains("result: PASS; exit 0"), "{prompt}");
    assert_eq!((r.jobs_of("test"), r.jobs_of("run")), (0, 1), "no test job was started for the covered lines");
}

#[test]
fn a_secret_in_done_check_output_is_redacted_from_the_file_the_entry_and_the_prompt() {
    let r = Root::new("secret", &[]);
    let (_id, e) = r.queued("notes.txt", &format!("token {PLANTED}\n"), "1. `broadsword run p --task <id> -- git show HEAD:notes.txt` -> prints the notes\n");
    let o = r.run_env(&["queue", "run", "--entry", &e], &[(PLANTED_NAME, PLANTED)]);
    assert_eq!(o.code, 0, "{}{}", o.stdout, o.stderr);
    let file = r.donecheck(&e);
    assert!(file.contains("    token [REDACTED]"), "the output line is there, redacted: {file}");
    let entry = fs::read_to_string(r.dir.join("state/queue").join(format!("{e}.entry"))).unwrap();
    for (what, text) in [("the .donecheck file", &file), ("the entry", &entry), ("the prompt", &r.prompt()), ("queue run's own output", &format!("{}{}", o.stdout, o.stderr))] {
        assert!(!text.contains(PLANTED), "{what} holds the planted secret");
    }
}

/// Review q-20261120-220118: a secret 3x the line cap (reviewer_check_tail_kb = 1 here) that starts just before the cut of an
/// over-long output line never shows in part: no piece of it of 4 bytes or more is in the .donecheck file or the prompt.
#[test]
fn a_secret_three_times_the_line_cap_spanning_the_cut_never_shows_in_part() {
    let r = Root::new("longsecret", &[("reviewer_check_tail_kb", "1")]);
    // letters with no vowel, so no ordinary word or hex id in the file or prompt shares a 4-letter piece with it
    let secret: String = (0..3 * 1024).map(|i: usize| char::from(b"QZXJVKWBGHMF"[(i * 7 + i / 12) % 12])).collect();
    let line = format!("{}{secret}end\n", "y".repeat(1024 - 10));
    let (_id, e) = r.queued("notes.txt", &line, "1. `broadsword run p --task <id> -- git show HEAD:notes.txt` -> prints the notes\n");
    let o = r.run_env(&["queue", "run", "--entry", &e], &[(PLANTED_NAME, &secret)]);
    assert_eq!(o.code, 0, "{}{}", o.stdout, o.stderr);
    let file = r.donecheck(&e);
    for (what, text) in [("the .donecheck file", file.clone()), ("the prompt", r.prompt())] {
        let leaks: Vec<&str> = (0..=secret.len() - 4).map(|i| &secret[i..i + 4]).filter(|p| text.contains(p)).take(5).collect();
        assert!(leaks.is_empty(), "{what} holds part of the secret: {leaks:?}");
    }
    // the line is there, cut and masked (the secret is longer than the kept part, so all of that part is masked)
    assert!(file.contains(&format!("    [REDACTED] [line cut: {} bytes, only the first 1024 kept (reviewer_check_tail_kb)]", line.len() - 1)), "{file}");
}

#[test]
fn a_done_check_command_past_its_timeout_is_killed_and_rejects_the_entry() {
    let r = Root::new("timeout", &[("done_check_timeout_seconds", "3")]);
    let wait = if cfg!(windows) { "ping -n 40 127.0.0.1" } else { "sleep 40" };
    let (_id, e) = r.queued("src/a.txt", "x\n", &format!("1. `broadsword run p --task <id> -- {wait}` -> never ends in time\n"));
    let t = Instant::now();
    let o = r.run(&["queue", "run", "--entry", &e]);
    let secs = t.elapsed().as_secs();
    assert_eq!(o.code, 5, "{}{}", o.stdout, o.stderr);
    assert_eq!(r.field(&e, "status"), "rejected", "reason = {}", r.field(&e, "reason"));
    assert!(r.field(&e, "reason").contains("timed out"), "{}", r.field(&e, "reason"));
    let dc = r.donecheck(&e);
    assert!(dc.contains("TIMED OUT after 3 s (done_check_timeout_seconds)"), "{dc}");
    // The command's own time as the queue recorded it (`result: ...; <ended>; <secs> s`), kill included. Not the whole
    // `queue run`, which also builds and tests `p` and so depends on machine load. The command itself would take ~40 s.
    let line = dc.lines().find(|l| l.trim_start().starts_with("result:") && l.contains("TIMED OUT")).unwrap_or_else(|| panic!("no result line for the timed-out command: {dc}"));
    let cmd_secs: f64 = line.trim_end().strip_suffix(" s").and_then(|l| l.rsplit("; ").next()).and_then(|n| n.parse().ok()).unwrap_or_else(|| panic!("no seconds in {line:?}"));
    println!("timed-out command: {cmd_secs:.1} s recorded; whole queue run {secs} s");
    assert!((3.0..25.0).contains(&cmd_secs), "the command was cut at its 3 s timeout, not waited for: {cmd_secs} s recorded ({line})");
    assert_eq!(r.calls(), 0);
}
